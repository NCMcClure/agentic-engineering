#!/usr/bin/env node
// docs/plugins.md, written from what the plugins themselves say: the catalog
// for the order and the pitch, each plugin.json for the version, each
// SKILL.md's frontmatter for the skills. Nothing in it is typed by hand, so it
// cannot drift from the tree: the gate regenerates it and fails a stale copy.
//
// It also writes the "## The areas" section of the entry skill, the one a
// person types: a row per area and, under each, what a person might want from
// it and the address that does it. The person's side of that (which areas are
// asked about together, what each is picked for, its few uses) is
// start-here.json beside the skill; whether a use names a real skill, and
// whether only a person can start it, is read from the tree. The rest of that
// skill is written by hand and never touched.
//
// Usage: node scripts/gen-guide.mjs [--write] [--root <dir>]
//
// Without --write it says whether each file is current and exits 1 if one is
// not.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parseFrontmatter, readJson } from "./lib.mjs";

export const GUIDE = "docs/plugins.md";

const cell = (text) => String(text ?? "").replace(/\s+/g, " ").replaceAll("|", "\\|").trim();

/** One plugin's skills, by name: how each is started and what its description says. */
function skillsOf(dir) {
  const skills = path.join(dir, "skills");
  if (!fs.existsSync(skills)) return [];
  return fs.readdirSync(skills, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort().flatMap((name) => {
    const file = path.join(skills, name, "SKILL.md");
    const fm = fs.existsSync(file) ? parseFrontmatter(fs.readFileSync(file, "utf8")) : null;
    return fm ? [{ name, hint: fm["argument-hint"] ?? "", byHand: String(fm["disable-model-invocation"]) === "true", description: fm.description ?? "" }] : [];
  });
}

/** The whole guide as text, for the checkout at `root`. */
export function guide(root) {
  const catalog = readJson(path.join(root, ".claude-plugin", "marketplace.json"));
  const local = catalog.plugins.filter((p) => typeof p.source === "string");
  const out = [
    "# The plugins",
    "",
    `Generated by \`node scripts/gen-guide.mjs --write\` from the catalog, each plugin's manifest, and each skill's own description. Do not edit it by hand: the gate fails a copy that has drifted.`,
    "",
    `Install any of them with \`/plugin install <name>@${catalog.name}\` after \`/plugin marketplace add\`. A skill marked *by hand* starts only when you type it; the rest the agent can start when its description fits.`,
    "",
    "| Plugin | Version | Skills | For |",
    "|---|---|---|---|",
  ];
  const plugins = local.map((entry) => {
    const dir = path.join(root, "plugins", entry.name);
    return { entry, manifest: readJson(path.join(dir, ".claude-plugin", "plugin.json")), skills: skillsOf(dir) };
  });
  for (const { entry, manifest, skills } of plugins) out.push(`| [${entry.name}](#${entry.name}) | ${manifest.version} | ${skills.length} | ${cell(entry.category)} |`);
  for (const { entry, manifest, skills } of plugins) {
    out.push("", `## ${entry.name}`, "", `${cell(entry.description)}`, "", `Version ${manifest.version}. [README](../plugins/${entry.name}/README.md), [changelog](../plugins/${entry.name}/CHANGELOG.md).`);
    if (!skills.length) continue;
    out.push("", "| Skill | Started | When |", "|---|---|---|");
    for (const s of skills) out.push(`| \`/${entry.name}:${s.name}${s.hint ? ` ${cell(s.hint)}` : ""}\` | ${s.byHand ? "by hand" : "by the agent, or by hand"} | ${cell(s.description)} |`);
  }
  return `${out.join("\n")}\n`;
}

// ---- the entry skill -----------------------------------------------------
export const ENTRY_PLUGIN = "agentcraft";
export const ENTRY_SKILL = "start-here";
export const ENTRY_FILE = `plugins/${ENTRY_PLUGIN}/skills/${ENTRY_SKILL}/SKILL.md`;
export const ENTRY_DATA = `plugins/${ENTRY_PLUGIN}/skills/${ENTRY_SKILL}/${ENTRY_SKILL}.json`;
export const AREAS_HEADING = "## The areas";
export const AREAS_END = "<!-- end of the generated areas section -->";
export const AREAS_TABLE_HEAD = "| Ask under | Area | A person picks it to |";
/** The one option a person is offered that is not an area; it rides with the last group. */
export const LEARN_MORE = "Learn more about the areas and their skills";

/**
 * The entry skill's data joined to the tree: its groups (the questions a
 * person is asked, in order), and every area they name, with each use's
 * address, whether it names a skill that is there (`found`), who the data
 * says starts it (`starts`), and whether only a person can (`person`).
 * `listed` is false for an area a group names and the data has no entry for;
 * `unknown` is the data's entries no group names. A missing or non-string
 * field reads as "", which the gate fails. Throws only when the data does not
 * parse. An area is a plugin today, and a use one of its skills.
 */
export function readEntry(root) {
  const data = readJson(path.join(root, ENTRY_DATA));
  const text = (value) => (typeof value === "string" ? value.trim() : "");
  const groups = (Array.isArray(data?.groups) ? data.groups : []).map((g) => ({ title: text(g?.title), header: text(g?.header), areas: (Array.isArray(g?.areas) ? g.areas : []).map(String) }));
  const order = groups.flatMap((g) => g.areas);
  const areas = order.map((name) => {
    const own = data?.areas?.[name];
    const byHand = new Map(skillsOf(path.join(root, "plugins", name)).map((s) => [s.name, s.byHand]));
    return {
      name,
      listed: own !== null && typeof own === "object",
      cue: text(own?.cue),
      how: text(own?.how),
      uses: (Array.isArray(own?.uses) ? own.uses : []).map((use) => {
        const to = text(use?.to);
        return { want: text(use?.want), to, starts: use?.starts ?? "agent", found: byHand.has(to), person: byHand.get(to) === true, address: `/${name}:${to}` };
      }),
    };
  });
  return { groups, areas, unknown: Object.keys(data?.areas ?? {}).filter((name) => !order.includes(name)) };
}

function areasSection(entry) {
  const byName = new Map(entry.areas.map((a) => [a.name, a]));
  const rows = entry.groups.flatMap((g) => g.areas.map((name) => `| ${cell(g.title)} (\`${cell(g.header)}\`) | \`${name}\` | ${cell(byName.get(name).cue)} |`));
  return [
    AREAS_HEADING,
    `Generated by \`scripts/gen-guide.mjs\` from \`${ENTRY_SKILL}.json\` beside this file and each skill's own frontmatter. Change those, never this section.`,
    [AREAS_TABLE_HEAD, "| --- | --- | --- |", ...rows].join("\n"),
    ...entry.areas.flatMap((a) => [
      `### ${a.name}`,
      ...(a.how ? [a.how] : []),
      ["| They want to | Hand off to | Starts it |", "| --- | --- | --- |", ...a.uses.map((u) => `| ${cell(u.want)} | \`${u.address}\` | ${u.starts === "person" ? "person" : "agent"} |`)].join("\n"),
    ]),
    AREAS_END,
  ].join("\n\n") + "\n";
}

/**
 * The entry skill as it should read: the hand-written text as it is, then the
 * generated section, which is the last thing in the file. Throws when the
 * data does not parse, and when the skill is not there to write into.
 */
export function renderEntry(root) {
  const file = path.join(root, ENTRY_FILE);
  if (!fs.existsSync(file)) throw new Error(`${ENTRY_FILE} is missing: ${ENTRY_SKILL}.json is there, and the skill it belongs to is written by hand`);
  const have = fs.readFileSync(file, "utf8");
  const at = have.indexOf(`\n${AREAS_HEADING}\n`);
  const head = at === -1 ? `${have.trimEnd()}\n\n` : have.slice(0, at + 1);
  return head + areasSection(readEntry(root));
}

/** Whether this checkout has an entry skill to generate for. */
export const hasEntry = (root) => fs.existsSync(path.join(root, ENTRY_DATA));

function main(argv) {
  const root = path.resolve(argv.includes("--root") ? argv[argv.indexOf("--root") + 1] : path.join(import.meta.dirname, ".."));
  const targets = [{ rel: GUIDE, render: () => guide(root) }, ...(hasEntry(root) ? [{ rel: ENTRY_FILE, render: () => renderEntry(root) }] : [])];
  let stale = 0;
  for (const { rel, render } of targets) {
    const file = path.join(root, rel);
    const want = render();
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (have === want) { console.log(`${rel} is current`); continue; }
    if (!argv.includes("--write")) { console.log(`${rel} is ${have === null ? "missing" : "stale"}: node scripts/gen-guide.mjs --write`); stale += 1; continue; }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, want);
    console.log(`wrote ${rel}`);
  }
  return stale ? 1 : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync.native(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
