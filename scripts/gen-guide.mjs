#!/usr/bin/env node
// docs/plugins.md, written from what the plugins themselves say: the catalog
// for the order and the pitch, each plugin.json for the version, each
// SKILL.md's frontmatter for the skills. Nothing in it is typed by hand, so it
// cannot drift from the tree: the gate regenerates it and fails a stale copy.
//
// Usage: node scripts/gen-guide.mjs [--write] [--root <dir>]
//
// Without --write it says whether docs/plugins.md is current and exits 1 if
// it is not.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { parseFrontmatter, readJson } from "./lib.mjs";

export const GUIDE = "docs/plugins.md";

const cell = (text) => String(text ?? "").replace(/\s+/g, " ").replaceAll("|", "\\|").trim();

/** One plugin's skills, by name: how each is started and what its description says. */
function skillsOf(dir) {
  const skills = path.join(dir, "skills");
  if (!fs.existsSync(skills)) return [];
  return fs.readdirSync(skills, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort().flatMap((name) => {
    const file = path.join(skills, name, "SKILL.md");
    const fm = fs.existsSync(file) ? parseFrontmatter(fs.readFileSync(file, "utf8")) : null;
    return fm ? [{ name, hint: fm["argument-hint"] ?? "", byHand: String(fm["disable-model-invocation"]) === "true", description: fm.description ?? "" }] : [];
  });
}

/** The whole guide as text, for the checkout at `root`. */
export function guide(root) {
  const catalog = readJson(path.join(root, ".claude-plugin", "marketplace.json"));
  const local = catalog.plugins.filter((p) => typeof p.source === "string");
  const out = [
    "# The plugins",
    "",
    `Generated by \`node scripts/gen-guide.mjs --write\` from the catalog, each plugin's manifest, and each skill's own description. Do not edit it by hand: the gate fails a copy that has drifted.`,
    "",
    `Install any of them with \`/plugin install <name>@${catalog.name}\` after \`/plugin marketplace add\`. A skill marked *by hand* starts only when you type it; the rest the agent can start when its description fits.`,
    "",
    "| Plugin | Version | Skills | For |",
    "|---|---|---|---|",
  ];
  const plugins = local.map((entry) => {
    const dir = path.join(root, "plugins", entry.name);
    return { entry, manifest: readJson(path.join(dir, ".claude-plugin", "plugin.json")), skills: skillsOf(dir) };
  });
  for (const { entry, manifest, skills } of plugins) out.push(`| [${entry.name}](#${entry.name}) | ${manifest.version} | ${skills.length} | ${cell(entry.category)} |`);
  for (const { entry, manifest, skills } of plugins) {
    out.push("", `## ${entry.name}`, "", `${cell(entry.description)}`, "", `Version ${manifest.version}. [README](../plugins/${entry.name}/README.md), [changelog](../plugins/${entry.name}/CHANGELOG.md).`);
    if (!skills.length) continue;
    out.push("", "| Skill | Started | When |", "|---|---|---|");
    for (const s of skills) out.push(`| \`/${entry.name}:${s.name}${s.hint ? ` ${cell(s.hint)}` : ""}\` | ${s.byHand ? "by hand" : "by the agent, or by hand"} | ${cell(s.description)} |`);
  }
  return `${out.join("\n")}\n`;
}

function main(argv) {
  const root = path.resolve(argv.includes("--root") ? argv[argv.indexOf("--root") + 1] : path.join(import.meta.dirname, ".."));
  const file = path.join(root, GUIDE);
  const want = guide(root);
  const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (have === want) { console.log(`${GUIDE} is current`); return 0; }
  if (!argv.includes("--write")) { console.log(`${GUIDE} is ${have === null ? "missing" : "stale"}: node scripts/gen-guide.mjs --write`); return 1; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, want);
  console.log(`wrote ${GUIDE}`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync.native(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
