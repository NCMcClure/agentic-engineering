// Each glyph as its row bytes, bit 4 the leftmost column.
const BITMAPS = new Map(Object.entries(GLYPHS).map(([ch, rows]) => [ch, Uint8Array.from(rows.split(" "), (r) => parseInt(r.replaceAll("#", "1").replaceAll(".", "0"), 2))]));

/** The row bytes (seven, or eight with a descender) of a printable ASCII character, or undefined. */
export const glyphRows = (ch) => BITMAPS.get(ch);

