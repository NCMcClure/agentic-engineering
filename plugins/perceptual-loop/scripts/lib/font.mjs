/** The text as printable ASCII: accents dropped, symbols spelled out, anything else '?'. */
export function ascii(text) {
  let out = "";
  for (const ch of String(text)) {
    if (ch >= " " && ch <= "~") { out += ch; continue; }
    if (SPELLED[ch] !== undefined) { out += SPELLED[ch]; continue; }
    const bare = ch.normalize("NFKD").replace(/[̀-ͯ]/g, "");
    out += /^[ -~]+$/.test(bare) ? bare : "?";
  }
  return out;
}

/** Width in pixels of a line of text at a scale, a whole cell per character. */
export const textWidth = (text, scale = 2) => ascii(text).length * CELL_W * scale;

/** The text cut to fit `width` pixels at a scale, ending in "..." when cut. */
export function fitText(text, width, scale = 2) {
  const t = ascii(text), room = Math.floor(width / (CELL_W * scale));
  if (t.length <= room) return t;
  return room <= 3 ? t.slice(0, Math.max(0, room)) : t.slice(0, room - 3) + "...";
}

/** The text broken at spaces into lines of at most `width` pixels; a word longer than a line is cut. */
export function wrapText(text, width, scale = 2) {
  const room = Math.max(1, Math.floor(width / (CELL_W * scale))), lines = [];
  let line = "";
  for (const word of ascii(text).split(/ +/).filter(Boolean)) {
    if (!line) line = word;
    else if (line.length + 1 + word.length <= room) line += " " + word;
    else { lines.push(line); line = word; }
    while (line.length > room) { lines.push(line.slice(0, room)); line = line.slice(room); }
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

/** Draw one line of text into an RGB8 picture with its cell's top-left at (x, y), clipped. */
export function drawText(img, x, y, text, colour, scale = 2) {
  const s = Math.max(1, Math.round(scale));
  let at = x;
  for (const ch of ascii(text)) {
    const rows = BITMAPS.get(ch);
    for (let r = 0; r < rows.length; r++) for (let c = 0; c < 5; c++) {
      if (!(rows[r] & (16 >> c))) continue;
      for (let dy = 0; dy < s; dy++) for (let dx = 0; dx < s; dx++) {
        const px = at + c * s + dx, py = y + r * s + dy;
        if (px < 0 || py < 0 || px >= img.width || py >= img.height) continue;
        const i = (py * img.width + px) * 3;
        img.data[i] = colour[0]; img.data[i + 1] = colour[1]; img.data[i + 2] = colour[2];
      }
    }
    at += CELL_W * s;
  }
  return at;
}
