#!/usr/bin/env node
// aw decisions: decision records and the glossary (references/decisions.md).
//
//   aw decisions new "<title>" [--slug s] [--status proposed]   the next NNNN-slug.md from the template, titled as
//                                                              the folder's latest records are (`# ADR 0014: T`)
//   aw decisions index [--check] [--adopt]                     write the generated README.md index
//   aw decisions lint [--json]                                 records, index and glossary
//
// Records live in `paths.decisions` (default .agents/decisions), one decision
// per file `NNNN-slug.md` with the sections Status, Sources, Context, Decision,
// Consequences. A record takes one amendment; after that a new record
// supersedes it. The glossary is `paths.glossary` (default .agents/CONTEXT.md):
// one term per row, defined once.
//
// The index README.md is generated when one of its first lines is the marker
// `aw decisions index` writes (GENERATED below). Any other README.md is
// hand-written and is never rewritten as a side effect: `new` appends one line
// to it, and `index` refuses to run over it until it is told to with --adopt.
import fs from "node:fs";
import path from "node:path";
import {
  AwError, Finding, appendListLine, atomicWrite, emit, fail, indexKind as kindOfIndex, ioOf, lineCount, linesLost, parseArgs, projectRoot,
  readText, realPath, rel, report, runMain, splitLines, template, today,
} from "../lib/common.mjs";
import { budget, configPath, loadConfig } from "../lib/config.mjs";

const USAGE = `usage: aw decisions <new|index|lint> [args]

  aw decisions new "<title>" [--slug s] [--status proposed] [--json]
                                             the next NNNN-slug.md from the template, titled as the folder's
                                             latest records are (\`# ADR 0014: T\`)
  aw decisions index [--check] [--adopt] [--json]   write the generated README.md index
  aw decisions lint [--json]                 records, index and glossary

Records live in paths.decisions (default .agents/decisions), one decision per file NNNN-slug.md with the sections
Status, Sources, Context, Decision, Consequences. A record takes one amendment; after that a new record supersedes
it. The glossary is paths.glossary (default .agents/CONTEXT.md): one term per row, defined once.

Status and Sources are read as a \`## Status\` section or, in the common ADR form, as a line above the first section:
\`- **Status:** accepted\`, \`**Status**: accepted\`, \`Status: accepted\`, a frontmatter \`status:\` (the same for
Sources and Date; a date is added to the status in the index).

The index README.md is generated when one of its first lines is the marker \`aw decisions index\` writes. Any other
is hand-written and never rewritten as a side effect: \`new\` appends one line to it, and \`index\` refuses to run
over it until it is told to with --adopt.

  DEC_NUMBER         a record whose name is not NNNN-slug.md, a number used twice, a heading with another number
  DEC_SECTIONS       a record without one of the five sections
  DEC_SIZE           a record over budgets.decisionLines
  DEC_AMENDED        more than one amendment section: write a new record that supersedes this one
  DEC_INDEX_STALE    README.md is missing, or a generated one differs from what \`aw decisions index\` writes
  DEC_INDEX_HANDWRITTEN  info: README.md is written by hand (kept as it is; \`aw decisions index --adopt\` converts it)
  GLOSSARY_MULTI     more than one glossary (the configured one, a root CONTEXT.md, one in the user docs)
  GLOSSARY_DUP_TERM  a term defined twice
  GLOSSARY_ROW_LONG  a row over budgets.glossaryRowChars`;

/** The sections of a record. */
export const SECTIONS = Object.freeze(["Status", "Sources", "Context", "Decision", "Consequences"]);
const NAME_RE = /^(\d{4})-([a-z0-9][a-z0-9-]*)\.md$/;
const HEADING = /^(#{1,6})\s+(.*?)\s*#*\s*$/;
// The title forms in use: `# 0014. Title`, `# ADR 0014: Title`, `# 0014: Title`, `# 0014 - Title`, `# ADR-0014: Title`
const TITLE = /^(ADR[\s-]*)?(\d{1,4})(\s*[.:—-]\s*)(.*)$/i;
const FORM_FROM_LAST = 5; // `new` follows the majority form of this many latest records
const INDEX = "README.md";
/** The marker of a generated index. A README.md without it among its first lines is hand-written. */
export const GENERATED = "<!-- Generated by `aw decisions index` from the records. Do not edit by hand. -->";
/** The marker follows the title and the one paragraph under it: it counts within this many lines. */
export const MARKER_WITHIN = 8;
const NO_RECORDS = "No records yet: `aw decisions new \"<title>\"` starts the first.";
/** The index `aw setup` wrote before the stub carried the marker: generated too. */
export const STUB_0_1_2 = `# Decisions\n\n${NO_RECORDS}\n`;
// `- **Status:** accepted`, `**Status**: accepted`, `Status: accepted`, a frontmatter `status: accepted`
const FIELD = /^\s*(?:[-*+]\s+)?(?:\*\*|__)?(status|sources?|date)\s*(?::\s*(?:\*\*|__)|(?:\*\*|__)\s*:|:)\s*(.*)$/i;
const DATED = /\d{4}-\d{2}-\d{2}/;
const FENCE = /^\s*(```|~~~)/;

const squash = (value) => String(value).split(/\s+/).filter(Boolean).join(" ");
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const isDir = (p) => {
  try { return fs.statSync(p).isDirectory(); } catch { return false; }
};
const isFile = (p) => {
  try { return fs.statSync(p).isFile(); } catch { return false; }
};

/** "missing", "generated" (it carries the marker, or is the stub of `aw setup`) or "handwritten". */
export function indexKind(index) {
  const kind = kindOfIndex(index, GENERATED, MARKER_WITHIN);
  if (kind === "handwritten" && (readText(index, "") ?? "").trim() === STUB_0_1_2.trim()) return "generated";
  return kind;
}

/** The records' folder (`paths.decisions`). */
export function decisionsDir(root, cfg) {
  return configPath(cfg, root, "decisions");
}

/**
 * The records, in file order: `{ path, rel, file, number, slug, title, heading_number, status, title_form,
 * sections: { name: line }, amendments, lines, text }`. `title_form` is what stands before the number, whether the
 * number has four digits, and what stands between it and the title; null for a heading without a number.
 */
export function scan(root, cfg) {
  const d = decisionsDir(root, cfg);
  const out = [];
  if (!isDir(d)) return out;
  for (const name of fs.readdirSync(d).sort(byName)) {
    const file = path.join(d, name);
    if (!isFile(file) || path.extname(name).toLowerCase() !== ".md" || [INDEX, "INDEX.md", "AGENTS.md", "CLAUDE.md"].includes(name)) continue;
    const text = readText(file, "") ?? "";
    const m = NAME_RE.exec(name);
    const rec = {
      path: file, rel: rel(file, root), file: name, number: m ? m[1] : null, slug: m ? m[2] : null, title: "", heading_number: null,
      status: "", title_form: null, sections: {}, amendments: 0, lines: lineCount(text), text,
    };
    const lines = splitLines(text);
    let fenced = false;
    const fields = {}; // the ADR form: Status / Sources / Date as a line above the first section
    let head = true;
    lines.forEach((line, i) => {
      if (FENCE.test(line)) fenced = !fenced;
      const h = fenced ? null : HEADING.exec(line);
      if (!h) {
        const f = head && !fenced ? FIELD.exec(line) : null;
        if (f) {
          const key = f[1].toLowerCase() === "source" ? "sources" : f[1].toLowerCase();
          fields[key] ??= [i + 1, squash(f[2].replace(/^[ \t*_]+|[ \t*_]+$/g, ""))];
        }
        return;
      }
      head = head && h[1].length < 2;
      const level = h[1].length;
      const name2 = h[2].trim();
      if (level === 1 && !rec.title) {
        const t = TITLE.exec(name2);
        rec.title = (t ? t[4] : name2).trim();
        rec.heading_number = t ? t[2].padStart(4, "0") : null;
        rec.title_form = t ? [t[1] || "", t[2].length === 4, t[3]] : null;
      } else if (level >= 2) {
        const bare = name2.replace(/:+$/, "").trim();
        const key = bare.charAt(0).toUpperCase() + bare.slice(1).toLowerCase();
        if (SECTIONS.includes(key)) rec.sections[key] ??= i + 1;
        else if (/^(amendment|amended|update|addendum)\b/i.test(name2)) rec.amendments += 1;
      }
    });
    const at = rec.sections.Status;
    if (at) {
      const first = lines.slice(at).find((line) => line.trim());
      if (first !== undefined) rec.status = first.startsWith("#") ? "" : squash(first);
    } else if (fields.status) {
      rec.status = fields.status[1];
      const date = fields.date?.[1] ?? "";
      if (rec.status && date && !DATED.test(rec.status)) rec.status += ` (${date})`;
    }
    for (const name2 of ["Status", "Sources"]) {
      if (fields[name2.toLowerCase()]) rec.sections[name2] ??= fields[name2.toLowerCase()][0];
    }
    out.push(rec);
  }
  return out;
}

/** The line of a record in the index: the house format, also appended to a hand-written index. */
export function recordLine(r) {
  return `- [${r.number} — ${r.title || r.slug}](${r.file})${r.status ? ` — ${r.status}` : ""}`;
}

/** The generated README.md for these records. */
export function buildIndex(records) {
  const lines = ["# Decisions", "", "One record per decision, numbered in the order they were made. A record is amended once; "
    + "after that a new record supersedes it.", "", GENERATED, ""];
  const numbered = records.filter((r) => r.number !== null);
  lines.push(...(numbered.length ? numbered.map(recordLine) : [NO_RECORDS]));
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

/**
 * The heading of a new record in the form the folder uses: the majority form of its latest records (the newest wins
 * a tie). Null in a folder without titled records: the template's own form stands.
 */
export function titleLine(records, number, title) {
  const forms = records.filter((r) => r.number !== null && r.title_form).map((r) => r.title_form).slice(-FORM_FROM_LAST);
  if (!forms.length) return null;
  const key = (f) => JSON.stringify(f);
  const score = (f) => [forms.filter((x) => key(x) === key(f)).length, forms.findLastIndex((x) => key(x) === key(f))];
  const [prefix, padded, sep] = forms.reduce((best, f) => {
    const [a, b] = [score(best), score(f)];
    return b[0] > a[0] || (b[0] === a[0] && b[1] > a[1]) ? f : best;
  });
  return `# ${prefix}${padded ? number : Number(number)}${sep}${title}`;
}

/** The glossaries the project has, the configured one first. More than one is GLOSSARY_MULTI. */
export function glossaryFiles(root, cfg) {
  const main = configPath(cfg, root, "glossary");
  const docs = configPath(cfg, root, "userDocs");
  const seen = new Set();
  const out = [];
  for (const p of [main, path.join(root, "CONTEXT.md"), path.join(docs, "CONTEXT.md"), path.join(root, ".agents", "CONTEXT.md"), path.join(docs, "glossary.md")]) {
    const key = realPath(p).toLowerCase();
    if (!seen.has(key) && isFile(p)) {
      seen.add(key);
      out.push(p);
    }
  }
  return out;
}

/** `[line number, term, the row]` of a glossary: table rows, `- **Term** …` items and `**Term**: …` paragraphs. */
export function glossaryRows(text) {
  const rows = [];
  let fenced = false;
  splitLines(text).forEach((line, i) => {
    if (FENCE.test(line)) {
      fenced = !fenced;
      return;
    }
    if (fenced) return;
    const s = line.trim();
    let term = null;
    if (s.startsWith("|")) {
      const cells = s.replace(/^\|+|\|+$/g, "").split("|").map((c) => c.trim());
      if (/^:?-{2,}:?$/.test(cells[0]) || ["term", "word", "name", ""].includes(cells[0].toLowerCase())) return;
      [term] = cells;
    } else {
      term = /^(?:[-*+]\s+)?\*\*(.+?)\*\*/.exec(s)?.[1] ?? null;
    }
    if (!term) return;
    term = term.replace(/[*`_]/g, "").trim().replace(/:+$/, "").trim();
    if (term) rows.push([i + 1, term, s]);
  });
  return rows;
}

/** What `aw decisions lint` and the doctor report: the records, their index and the glossary. */
export function findings(root, cfg = null) {
  const config = cfg ?? loadConfig(root);
  const out = [];
  const records = scan(root, config);
  const index = path.join(decisionsDir(root, config), INDEX);
  const numbers = new Map();
  for (const r of records) {
    if (r.number === null) {
      out.push(new Finding("DEC_NUMBER", "warning", r.rel, 0, "the file name must be NNNN-slug.md (four digits, kebab-case slug)"));
    } else {
      if (numbers.has(r.number)) out.push(new Finding("DEC_NUMBER", "warning", r.rel, 0, `the number ${r.number} is also ${numbers.get(r.number)}`));
      else numbers.set(r.number, r.file);
      if (r.heading_number && r.heading_number !== r.number) {
        out.push(new Finding("DEC_NUMBER", "warning", r.rel, 1, `the heading says ${r.heading_number}, the file name ${r.number}`));
      }
    }
    const missing = SECTIONS.filter((s) => !(s in r.sections));
    if (missing.length) out.push(new Finding("DEC_SECTIONS", "warning", r.rel, 0, `lacks the section${missing.length > 1 ? "s" : ""}: ${missing.join(", ")}`));
    const limit = budget(config, "decisionLines");
    if (r.lines > limit) {
      out.push(new Finding("DEC_SIZE", "warning", r.rel, 0, `${r.lines} lines, the budget is ${limit}: a record holds one decision; measurements belong in memory`));
    }
    if (r.amendments > 1) {
      out.push(new Finding("DEC_AMENDED", "warning", r.rel, 0,
        `${r.amendments} amendment sections: a record takes one; write a new record that supersedes this one`));
    }
  }
  if (records.length) {
    const have = readText(index);
    if (have !== null && indexKind(index) === "handwritten") {
      const n = linesLost(have, buildIndex(records));
      out.push(new Finding("DEC_INDEX_HANDWRITTEN", "info", rel(index, root), 0,
        `written by hand (${n} line${n === 1 ? "" : "s"} would be lost by generating it): \`aw decisions new\` adds one line to it; \`aw decisions index --adopt\` converts it`));
    } else if (have === null || have !== buildIndex(records)) {
      out.push(new Finding("DEC_INDEX_STALE", "warning", rel(index, root), 0, `${have === null ? "is missing" : "differs from the records"} (aw decisions index)`));
    }
  }
  const glossaries = glossaryFiles(root, config);
  if (glossaries.length > 1) {
    out.push(new Finding("GLOSSARY_MULTI", "warning", rel(glossaries[1], root), 0,
      `more than one glossary: ${glossaries.map((g) => rel(g, root)).join(", ")} (the one home is ${rel(configPath(config, root, "glossary"), root)})`));
  }
  const limit = budget(config, "glossaryRowChars");
  for (const g of glossaries) {
    const seen = new Map();
    for (const [n, term, row] of glossaryRows(readText(g, "") ?? "")) {
      const key = term.toLowerCase();
      if (seen.has(key)) out.push(new Finding("GLOSSARY_DUP_TERM", "warning", rel(g, root), n, `\`${term}\` is defined on line ${seen.get(key)} too`));
      else seen.set(key, n);
      const size = [...row].length;
      if (size > limit) {
        out.push(new Finding("GLOSSARY_ROW_LONG", "warning", rel(g, root), n,
          `the row of \`${term}\` is ${size} characters, the budget is ${limit}: define the word; the why goes into a decision`));
      }
    }
  }
  return out;
}

/** Write the index when it is missing, or generated and stale; a hand-written one only with `adopt`. Gives its path when written. */
export function writeIndex(root, cfg, { adopt = false } = {}) {
  const records = scan(root, cfg);
  const d = decisionsDir(root, cfg);
  const index = path.join(d, INDEX);
  if (!isDir(d) || (!adopt && indexKind(index) === "handwritten")) return null;
  const text = buildIndex(records);
  if (readText(index) === text) return null;
  atomicWrite(index, text);
  return rel(index, root);
}

// ------------------------------------------------------------------------------------------------------- commands

const context = (io) => {
  const root = projectRoot(io.cwd);
  return [root, loadConfig(root)];
};

function start(args, io) {
  const { values, positionals } = parseArgs(args, { slug: { type: "string" }, status: { type: "string" }, json: { type: "boolean" } });
  if (positionals.length !== 1) throw new AwError('new takes one title: aw decisions new "<title>"');
  const [root, cfg] = context(io);
  const title = squash(positionals[0]);
  const slug = values.slug || title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60).replace(/^-+|-+$/g, "");
  if (!slug || !/^[a-z0-9][a-z0-9-]*$/.test(slug)) return fail(io, "aw decisions new: the slug is kebab-case (give one with --slug)");
  const records = scan(root, cfg);
  if (records.some((r) => r.slug === slug)) return fail(io, `aw decisions new: a record with the slug \`${slug}\` exists`);
  const number = String(Math.max(0, ...records.filter((r) => r.number).map((r) => Number(r.number))) + 1).padStart(4, "0");
  const d = decisionsDir(root, cfg);
  const file = path.join(d, `${number}-${slug}.md`);
  let text = template("decision.md", { number, title, status: values.status ?? "proposed", date: today(), slug });
  const heading = titleLine(records, number, title);
  // The folder's own title form, so its index stays of one kind.
  if (heading && text.startsWith("# ")) text = `${heading}\n${text.slice(text.indexOf("\n") + 1)}`;
  atomicWrite(file, text);
  const index = path.join(d, INDEX);
  let written;
  if (indexKind(index) === "handwritten") {
    // A hand-written index says more than the records' titles: it gets this record's line and nothing else.
    const rec = scan(root, cfg).find((r) => r.path === file);
    written = appendListLine(index, recordLine(rec)) ? rel(index, root) : null;
  } else {
    written = writeIndex(root, cfg);
  }
  if (values.json) emit(io, { path: rel(file, root), number, index: written }, true);
  else emit(io, rel(file, root));
  return 0;
}

function index(args, io) {
  const { values } = parseArgs(args, { check: { type: "boolean" }, adopt: { type: "boolean" }, json: { type: "boolean" } });
  const [root, cfg] = context(io);
  const json = values.json === true;
  if (values.check) {
    const stale = findings(root, cfg).filter((f) => f.code === "DEC_INDEX_STALE" || f.code === "DEC_INDEX_HANDWRITTEN");
    return report(io, stale, { json, title: "decision index", cfg });
  }
  const file = path.join(decisionsDir(root, cfg), INDEX);
  const byHand = indexKind(file) === "handwritten";
  if (byHand && !values.adopt) {
    const where = rel(file, root);
    const gone = linesLost(readText(file, "") ?? "", buildIndex(scan(root, cfg)));
    if (json) {
      emit(io, { refused: true, handwritten: [{ path: where, linesLost: gone }], written: [] }, true);
      return 2;
    }
    return fail(io, [
      `aw decisions index: ${where} is written by hand; nothing was written.`,
      "Generating it replaces the whole file with one line per record (number, title, status): "
        + `${gone} line${gone === 1 ? " says" : "s say"} something else today, and that text would be gone.`,
      "First move what those lines say into the records, then run `aw decisions index --adopt`.",
      "Until then `aw decisions new` adds one line to this index and changes nothing else of it.",
    ].join("\n"));
  }
  const changed = writeIndex(root, cfg, { adopt: values.adopt === true });
  const adopted = changed && byHand ? [changed] : [];
  if (json) emit(io, { written: changed ? [changed] : [], adopted }, true);
  else emit(io, changed ? `${adopted.length ? "adopted" : "wrote"} ${changed}` : "the decision index is up to date");
  return 0;
}

function lint(args, io) {
  const { values } = parseArgs(args, { json: { type: "boolean" } });
  const [root, cfg] = context(io);
  return report(io, findings(root, cfg), { json: values.json === true, title: `decisions: ${scan(root, cfg).length} records`, cfg });
}

const ACTIONS = { new: start, index, lint };

export async function main(argv, io) {
  io = ioOf(io);
  const [action, ...rest] = argv;
  if (action === "-h" || action === "--help" || rest.includes("--help") || rest.includes("-h")) {
    emit(io, USAGE);
    return 0;
  }
  if (!Object.hasOwn(ACTIONS, action ?? "")) {
    emit(io, USAGE);
    return 2;
  }
  return ACTIONS[action](rest, io);
}

runMain(import.meta.url, main);
