const isObject = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const isDir = (p) => {
  try { return fs.statSync(p).isDirectory(); } catch { return false; }
};
const isFile = (p) => {
  try { return fs.statSync(p).isFile(); } catch { return false; }
};
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const under = (p, dir) => p === dir || p.startsWith(dir + path.sep);
const ascii = (s) => s.replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
/** A value as one line of JSON with a space after each comma and colon: how a message quotes a config value. */
function inline(value) {
  if (Array.isArray(value)) return `[${value.map(inline).join(", ")}]`;
  if (isObject(value)) return `{${Object.entries(value).map(([k, v]) => `${ascii(JSON.stringify(k))}: ${inline(v)}`).join(", ")}}`;
  return ascii(JSON.stringify(value ?? null));
}

/** The heading a finding code is listed under in the report. */
export function groupOf(code) {
  return GROUPS.find(([, prefixes]) => prefixes.some((p) => code.startsWith(p)))?.[0] ?? "Other";
}

/** CONFIG_INVALID findings: a file that does not parse, a key of the wrong shape, a pattern that is no regular expression. */
export function configFindings(cfg, root) {
  const out = [];
  const where = cfg._path ? rel(cfg._path, root) : CONFIG;
  const bad = (message) => out.push(new Finding("CONFIG_INVALID", "critical", where, 0, message));
  if (cfg._error) return [new Finding("CONFIG_INVALID", "critical", where, 0, `${cfg._error} (the defaults apply until it is fixed)`)];
  if (!cfg._path) return out;
  const { version } = cfg;
  if (!Number.isInteger(version) || version > CONFIG_VERSION || version < 1) bad(`"version" is ${inline(version)}; this plugin reads version ${CONFIG_VERSION}`);
  for (const [key, kind] of Object.entries(SHAPES)) {
    if (key in cfg && !(kind === OBJECT ? isObject(cfg[key]) : Array.isArray(cfg[key]))) bad(`"${key}" must be ${kind}`);
  }
  if ("name" in cfg && typeof cfg.name !== "string") bad("\"name\" must be a string: the project's name, when it is not its folder's");
  if (Array.isArray(cfg.accept)) for (const problem of acceptEntries(cfg)[1]) bad(problem);
  const guard = isObject(cfg.guard) ? cfg.guard : {};
  for (const key of ["ownerFiles", "generated", "rules", "agentVarAliases"]) {
    if (key in guard && !Array.isArray(guard[key])) bad(`"guard.${key}" must be a list`);
  }
  const patterns = [];
  const listed = (value) => (Array.isArray(value) ? value : value === null || value === undefined ? [] : [value]);
  // A `match` (regular expressions, or { pattern, unless } objects) and an `unless` (regular expressions), as the guard reads them.
  const take = (what, match, unless) => {
    for (const m of listed(match)) {
      if (isObject(m)) {
        if (typeof m.pattern !== "string") {
          bad(`${what}: a match entry is a regular expression or {"pattern": …, "unless": […]}; ${inline(m)} has no "pattern"`);
          continue;
        }
        patterns.push([what, m.pattern]);
        take(what, [], m.unless);
      } else {
        patterns.push([what, m]);
      }
    }
    for (const u of listed(unless)) patterns.push([`${what} (unless)`, u]);
  };
  for (const g of Array.isArray(guard.generated) ? guard.generated : []) patterns.push(["guard.generated", isObject(g) ? g.match ?? null : null]);
  for (const r of Array.isArray(guard.rules) ? guard.rules : []) {
    const some = (v) => (Array.isArray(v) ? v.length > 0 : Boolean(v));
    if (!isObject(r) || !r.id || !some(r.match)) {
      bad("every guard.rules entry is an object with \"id\" and \"match\"");
      continue;
    }
    take(`guard.rules[${r.id}]`, r.match, r.unless);
  }
  for (const [name, spec] of Object.entries(isObject(cfg.resources) ? cfg.resources : {})) {
    if (!isObject(spec)) {
      bad(`"resources.${name}" must be an object`);
      continue;
    }
    if (![undefined, null, "project", "machine"].includes(spec.scope)) bad(`"resources.${name}.scope" is "project" or "machine"`);
    take(`resources.${name}`, spec.match, spec.unless);
  }
  for (const run of Array.isArray(cfg.runs) ? cfg.runs : []) {
    if (isObject(run)) take(`runs[${run.id ?? null}]`, run.match, run.unless);
  }
  for (const [what, pattern] of patterns) {
    if (typeof pattern !== "string") {
      // What guard.generated matches is the guard's to read: only a pattern written as one is tried here.
      if (what !== "guard.generated") bad(`${what}: ${inline(pattern)} is not a regular expression (a string)`);
      continue;
    }
    try {
      new RegExp(String(pattern));
    } catch (e) {
      bad(`${what}: the pattern '${pattern}' is not a regular expression (${e.message})`);
    }
  }
  return out;
}

/** The root AGENTS.md (status prose, the plugins section) and the generated contracts page. */
export function rootFindings(root, cfg) {
  const out = [];
  const agents = readText(path.join(root, "AGENTS.md"));
  if (agents) {
    let fenced = false;
    splitLines(agents).some((line, i) => {
      if (FENCE.test(line)) fenced = !fenced;
      if (!fenced && (/^#{1,6}\s+(Status|Current status|Done|Progress|Changelog)\b/i.test(line) || /^\*\*Status\b[^*]*\*\*/i.test(line.trim()))) {
        out.push(new Finding("ROOT_STATUS_PROSE", "info", "AGENTS.md", i + 1,
          "status prose in the root file, which every session loads: status lives in the status memory and on the board"));
        return true;
      }
      return false;
    });
  }
  if (cfg._path && agents !== null) {
    const block = pluginsBlock(cfg);
    const have = PLUGINS_BLOCK.exec(agents);
    if (block && !have) {
      out.push(new Finding("ROOT_PLUGINS", "warning", "AGENTS.md", 0,
        "no § Agent plugins: sessions and sub-agents are not told which plugin skills this project works with (aw setup --apply writes the section)"));
    } else if (have && have[0] !== block) {
      out.push(new Finding("ROOT_PLUGINS", "warning", "AGENTS.md", agents.slice(0, have.index).split("\n").length,
        "§ Agent plugins differs from the installed plugin's text or the config's \"plugins\" list (aw setup --apply rewrites the section)"));
    }
  }
  if (cfg._path) {
    const contract = path.join(root, ".agents", "README.md");
    const text = readText(contract);
    const where = rel(contract, root);
    if (text === null) {
      out.push(new Finding("CONTRACT_MISSING", "warning", where, 0, "the generated contracts page is missing (aw setup --apply writes it)"));
    } else {
      const m = STAMP.exec(text);
      const version = pluginVersion();
      if (!m) out.push(new Finding("CONTRACT_STALE", "warning", where, 0, "carries no agent-works version stamp (aw setup --apply regenerates it)"));
      else if (m[1] !== version) {
        out.push(new Finding("CONTRACT_STALE", "warning", where, 0, `generated by agent-works ${m[1]}, installed is ${version} (aw setup --apply regenerates it)`));
      }
      const lines = lineCount(text);
      const limit = budget(cfg, "contractLines");
      if (lines > limit) out.push(new Finding("CONTRACT_STALE", "warning", where, 0, `${lines} lines, the budget is ${limit}`));
    }
  }
  return out;
}

const list = (dir) => {
  try { return fs.readdirSync(dir).sort(byName); } catch { return []; }
};

/** Agent material under the user-docs folder. That folder is for user-facing documentation only. */
export function docsFindings(root, cfg) {
  const docs = configPath(cfg, root, "userDocs");
  const out = [];
  if (!isDir(docs)) return out;
  const warn = (p, message) => out.push(new Finding("DOCS_AGENT_FILE", "warning", rel(p, root), 0, message));
  const homes = { decisions: rel(configPath(cfg, root, "decisions"), root), glossary: rel(configPath(cfg, root, "glossary"), root) };
  if (["decisions", "glossary", "memory", "contracts", "briefs"].some((k) => under(configPath(cfg, root, k), docs))) {
    warn(docs, "the config keeps an agent home under the user-docs folder: agent files live under .agents/");
  }
  for (const name of ["adr", "adrs", "decisions"]) {
    const d = path.join(docs, name);
    if (isDir(d) && list(d).some((n) => path.extname(n).toLowerCase() === ".md")) {
      warn(d, `decision records under the user docs: \`git mv ${rel(d, root)} ${homes.decisions}\`, then \`aw decisions index\``);
    }
  }
  // One file may answer to two of these names where the file system folds case: it is one glossary.
  const glossary = ["CONTEXT.md", "glossary.md", "GLOSSARY.md"].map((name) => path.join(docs, name)).find(isFile);
  if (glossary) warn(glossary, `a glossary under the user docs: \`git mv ${rel(glossary, root)} ${homes.glossary}\``);
  for (const name of list(docs).filter((n) => n.endsWith(".md"))) {
    const f = path.join(docs, name);
    if (/^\d{3,4}-/.test(name) && /^##\s+(Status|Decision)\b/m.test(readText(f, "") ?? "")) {
      warn(f, `a decision record under the user docs: move it to ${homes.decisions}`);
    }
  }
  for (const name of ["AGENTS.md", "agents", "memory", "briefs"]) {
    const p = path.join(docs, name);
    if (fs.existsSync(p)) warn(p, "agent material under the user docs: its home is under .agents/");
  }
  return out;
}

function markdownUnder(dir) {
  const out = [];
  const walk = (d) => {
    for (const name of list(d)) {
      const full = path.join(d, name);
      if (isDir(full)) walk(full);
      else if (name.endsWith(".md") && isFile(full)) out.push(full);
    }
  };
  walk(dir);
  return out;
}

/** The briefs folder: a brief over its budget, a brief git does not track. */
export function briefFindings(root, cfg) {
  const briefs = configPath(cfg, root, "briefs");
  const out = [];
  if (!isDir(briefs)) return out;
  const [code, listed] = git(["ls-files", "-z", "--", rel(briefs, root)], root);
  const tracked = code === 0 ? new Set(listed.split("\0").filter(Boolean)) : null;
  for (const f of markdownUnder(briefs)) {
    const where = rel(f, root);
    const isRound = path.relative(briefs, f).split(path.sep).includes("rounds");
    const limit = budget(cfg, isRound ? "roundBriefLines" : "briefLines");
    const lines = lineCount(readText(f, "") ?? "");
    if (lines > limit) {
      out.push(new Finding("BRIEF_SIZE", "warning", where, 0, `${lines} lines, the budget is ${limit}: a brief says what this round needs; rules live in AGENTS.md`));
    }
    if (tracked !== null && !tracked.has(where)) {
      out.push(new Finding("BRIEF_UNTRACKED", "warning", where, 0, "git does not track it: a rule that only a scratch brief holds is lost with it"));
    }
  }
  return out.sort((a, b) => byName(a.path, b.path));
}

/** How far the walk for stray briefs goes: folders below the top that are looked into, and the entries a folder may have before it is passed over as build output or data. */
export const STRAY = { depth: 3, entries: 3000 };
const STRAY_SKIP = [".git", "node_modules"];
const STRAY_SKIP_REL = [".claude/worktrees", ".claude/agents", ".claude/skills", ".claude/commands"];

/**
 * Markdown named like a brief or a hand-over for agents that lies outside the briefs folder.
 *
 * The working tree is walked as it is on disk, so git-ignored scratch and run-output folders are read: that is where
 * such files hide. Kept cheap: three folders deep, no heavy or foreign trees, no folder of thousands.
 */
export function strayBriefFindings(root, cfg) {
  const spec = isObject(cfg.briefs) ? cfg.briefs : {};
  const given = "stray" in spec ? spec.stray : DEFAULTS.briefs.stray;
  const globs = Array.isArray(given) ? given.map((g) => String(g).toLowerCase()) : [];
  if (!globs.length) return [];
  const briefs = configPath(cfg, root, "briefs");
  // The homes of agent files hold cards, memories and records whose names may say "brief": they are in their home.
  const homes = new Set([
    ...["briefs", "memory", "kanban", "decisions", "contracts", "plan"].map((k) => realPath(configPath(cfg, root, k))),
    ...STRAY_SKIP_REL.map((r) => realPath(path.join(root, r))), realPath(path.join(root, OLD_BOARD)),
    realPath(PLUGIN_ROOT), // the plugin's own templates, when the project is the plugin
  ]);
  const skipNames = new Set([...hubs.SKIP_DIRS, ...STRAY_SKIP]);
  skipNames.delete(".agents");
  const out = [];
  const visit = (d, depth) => {
    let entries;
    try { entries = fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => byName(a.name, b.name)); } catch { return; }
    if (entries.length > STRAY.entries) return;
    for (const e of entries) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) {
        if (depth < STRAY.depth && !skipNames.has(e.name) && !homes.has(realPath(p))) visit(p, depth + 1);
      } else if (e.isFile() && e.name.toLowerCase().endsWith(".md") && globs.some((g) => fnmatch(e.name.toLowerCase(), g))) {
        out.push(new Finding("BRIEF_STRAY", "warning", rel(p, root), 0,
          `named like a brief or a hand-over for agents, outside ${rel(briefs, root)}: no agent finds it there. Move what holds for every round into ${rel(path.join(briefs, "common.md"), root)} `
          + "and each lasting fact to its home (a rule: AGENTS.md; a lesson: memory; a task: a card), then delete the file"));
      }
    }
  };
  visit(root, 0);
  return out;
}

/** Tasks kept in two places: cards in the old and the new board folder, or cards beside another `tasks.home`. */
export function tasksFindings(root, cfg) {
  const main = mainRoot(root) ?? root;
  const fresh = configPath(cfg, main, "kanban");
  const old = path.join(main, OLD_BOARD);
  const cards = (d) => (isDir(d) ? list(d).filter((n) => /^\d+-.*\.md$/.test(n)).length : 0);
  const out = [];
  if (fresh !== old && cards(fresh) && cards(old)) {
    out.push(new Finding("TASKS_TWO_HOMES", "warning", rel(old, main), 0, `cards in both ${rel(old, main)} and ${rel(fresh, main)}: move the old ones over`));
  }
  const home = String(cfg.tasks?.home || "kanban");
  if (home !== "kanban" && (cards(fresh) || cards(old))) {
    out.push(new Finding("TASKS_TWO_HOMES", "warning", rel(cards(fresh) ? fresh : old, main), 0,
      `tasks.home is "${home}", and the kanban folder holds cards too: one home for tasks`));
  }
  return out;
}

/** Run one check; a check that throws is named in `failed` and gives no findings, so it cannot hide the others. */
export async function safe(name, call, failed) {
  try {
    return [...(await call())];
  } catch (e) {
    failed[name] = `${e?.name ?? "Error"}: ${e?.message ?? e}`;
    return [];
  }
}

/**
 * The board's own findings, through the module that reads the board: its `findings(root)`. A plugin without that
 * module has no board to check; one that is there and cannot answer is a check that did not run.
 */
async function boardFindings(root, mods) {
  let mod = mods?.board;
  if (mod === undefined) {
    const file = path.join(HERE, "io.mjs");
    if (!fs.existsSync(file)) return [];
    mod = await import(pathToFileURL(file).href);
  }
  if (typeof mod?.findings !== "function") throw new Error("scripts/io.mjs exports no findings");
  const found = await mod.findings(root);
  return (Array.isArray(found) ? found : []).map((f) => (f instanceof Finding ? f : new Finding(f.code, f.level, f.path ?? "", f.line ?? 0, f.message ?? "")));
}

/** The sizes the baseline compares: the root file, the memory tree, the status memory, the decision records. */
export function sizes(root, cfg) {
  const out = {};
  const agents = readText(path.join(root, "AGENTS.md"));
  out.rootAgentsLines = agents !== null ? lineCount(agents) : 0;
  out.rootAgentsBytes = agents !== null ? Buffer.byteLength(agents, "utf8") : 0;
  try {
    const tree = memory.scan(root, cfg);
    out.memoryFiles = tree.memories.length;
    out.memoryFolders = tree.folders.length;
    out.memoryLines = tree.memories.reduce((sum, e) => sum + e.lines, 0);
    out.statusLines = tree.memories.find((e) => e.fields?.type === "status")?.lines ?? 0;
  } catch { /* the memory check says what is wrong with the tree */ }
  try {
    out.decisions = decisions.scan(root, cfg).length;
  } catch { /* the decisions check says what is wrong with the folder */ }
  return out;
}

/**
 * Every check, as `{ findings, accepted, failed: { check: error }, sizes, hubs, config }`.
 *
 * `findings` are the ones that count: what `accept` in the config took out is under `accepted`, and an entry of
 * that list that took nothing is reported here (ACCEPT_UNUSED), where every check has run. `mods.board` hands in
 * the board's module (a test does).
 */
export async function collect(root, { mods = null } = {}) {
  const cfg = loadConfig(root);
  const failed = {};
  const found = [];
  let hubCount = 0;
  const run = async (name, call) => found.push(...await safe(name, call, failed));
  await run("config", () => configFindings(cfg, root));
  await run("hubs", () => {
    const res = hubs.verify(root, [], cfg);
    hubCount = res.hubs;
    return res.findings;
  });
  await run("root", () => rootFindings(root, cfg));
  await run("memory", () => memory.findings(root, cfg));
  await run("decisions", () => decisions.findings(root, cfg));
  await run("links", () => links.findings(root, cfg).findings);
  await run("dup", () => dup.findings(root, cfg));
  await run("twins", () => (cfg._path && twins.MODES.includes(twins.modeOf(cfg)) ? twins.findings(root, cfg) : []));
  await run("kanban", () => boardFindings(root, mods));
  await run("tasks", () => tasksFindings(root, cfg));
  await run("briefs", () => briefFindings(root, cfg));
  await run("stray briefs", () => strayBriefFindings(root, cfg));
  await run("docs", () => docsFindings(root, cfg));
  const [kept, accepted, entries] = splitAccepted(sortFindings(found), cfg);
  const where = cfg._path ? rel(cfg._path, root) : CONFIG;
  for (const e of entries) {
    if (e.used || Object.keys(failed).length) continue; // a check that did not run may be the one the entry is for
    const what = `accept[${e.index}] (${e.code} at ${e.path})`;
    kept.push(new Finding("ACCEPT_UNUSED", "info", where, 0, e.critical
      ? `${what} matches only a critical finding, and a critical finding is never accepted: repair it, and remove the entry`
      : `${what} matches no finding: remove the entry`));
  }
  return { findings: sortFindings(kept), accepted, failed, sizes: sizes(root, cfg), hubs: hubCount, config: cfg._path ? rel(cfg._path, root) : null };
}

/** How many findings each code has, by code. */
export function countsByCode(found) {
  const out = {};
  for (const code of found.map((f) => f.code).sort(byName)) out[code] = (out[code] ?? 0) + 1;
  return out;
}

/** Where `--baseline` keeps a project's numbers. */
export function baselinePath(root, env = process.env) {
  return path.join(projectHome(root, env), "baseline.json");
}

/** What moved since the baseline: `{ at, sizes: { key: [then, now] }, codes: { code: [then, now] } }`. */
export function compare(now, then) {
  const moved = (a, b) => Object.fromEntries([...new Set([...Object.keys(a), ...Object.keys(b)])].sort(byName)
    .filter((k) => (a[k] ?? 0) !== (b[k] ?? 0)).map((k) => [k, [a[k] ?? 0, b[k] ?? 0]]));
  return { at: then.at ?? null, sizes: moved(isObject(then.sizes) ? then.sizes : {}, now.sizes), codes: moved(isObject(then.codes) ? then.codes : {}, now.codes) };
}

const groupNames = [...GROUPS.map(([name]) => name), "Other"];

/** The report as text. `max` findings are listed per code; `listAccepted` lists the accepted ones with their why. */
export function textReport(doc, found, { max = 8, listAccepted = false } = {}) {
  const lines = [`agent-works doctor — ${doc.project}${doc.config ? "" : "   (no .agents/agent-works.json: the defaults apply; aw setup --plan)"}`];
  for (const name of groupNames) {
    const mine = found.filter((f) => groupOf(f.code) === name);
    if (!mine.length) continue;
    lines.push("", `${name} (${mine.length})`);
    const shown = new Map();
    for (const f of mine) {
      shown.set(f.code, (shown.get(f.code) ?? 0) + 1);
      if (shown.get(f.code) <= max) lines.push(`  ${f.text()}`);
    }
    for (const [code, n] of shown) if (n > max) lines.push(`  … ${n - max} more ${code} (--json or --all lists them)`);
  }
  for (const [check, why] of Object.entries(doc.failed)) lines.push("", `check "${check}" did not run: ${why}`);
  lines.push("", `sizes: ${Object.entries(doc.sizes).map(([k, v]) => `${k} ${v}`).join(", ")}`);
  const b = doc.baseline;
  if (b && (Object.keys(b.sizes).length || Object.keys(b.codes).length)) {
    lines.push(`since the baseline of ${b.at}:`);
    for (const [k, [a, z]] of Object.entries({ ...b.sizes, ...b.codes })) lines.push(`  ${k}: ${a} -> ${z}`);
  } else if (b) {
    lines.push(`nothing moved since the baseline of ${b.at}`);
  }
  if (doc.baselineWritten) lines.push(`baseline written: ${doc.baselineWritten}`);
  const accepted = doc.accepted ?? [];
  if (accepted.length && listAccepted) {
    lines.push("", `Accepted (${accepted.length})`);
    for (const a of accepted) lines.push(`  ${a.code.padEnd(22)} ${a.path} — ${a.why}`);
  }
  const c = doc.summary;
  lines.push("");
  if (accepted.length && !listAccepted) lines.push(acceptedLine(accepted));
  lines.push(`doctor: ${c.critical} critical, ${c.warning} warning, ${c.info} info`);
  return lines.join("\n");
}

const escapeHtml = (value) => String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#x27;");

/** The report as one self-contained page. */
export function htmlReport(doc, found) {
  const e = escapeHtml;
  const rows = [];
  for (const name of groupNames) {
    const mine = found.filter((f) => groupOf(f.code) === name);
    if (!mine.length) continue;
    rows.push(`<h2>${e(name)} <small>${mine.length}</small></h2><table>`);
    for (const f of mine) {
      const where = e(f.path + (f.line ? `:${f.line}` : ""));
      rows.push(`<tr class="${e(f.level)}"><td>${e(f.level)}</td><td><code>${e(f.code)}</code></td><td><code>${where}</code></td><td>${e(f.message)}</td></tr>`);
    }
    rows.push("</table>");
  }
  const accepted = doc.accepted ?? [];
  if (accepted.length) {
    rows.push(`<h2>Accepted <small>${accepted.length}</small></h2><table>`);
    for (const a of accepted) rows.push(`<tr class="info"><td>accepted</td><td><code>${e(a.code)}</code></td><td><code>${e(a.path)}</code></td><td>${e(a.why)}</td></tr>`);
    rows.push("</table>");
  }
  const c = doc.summary;
  const sizeItems = Object.entries(doc.sizes).map(([k, v]) => `<li>${e(k)}: ${e(v)}</li>`).join("");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>agent-works doctor: ${e(doc.project)}</title>
<style>
:root { color-scheme: light dark; }
body { font: 14px/1.5 system-ui, sans-serif; margin: 2rem auto; max-width: 70rem; padding: 0 1rem; }
h1 { font-size: 1.3rem; } h2 { font-size: 1rem; margin-top: 1.6rem; } small { opacity: .6; font-weight: normal; }
table { border-collapse: collapse; width: 100%; } td { padding: .2rem .5rem; vertical-align: top; border-top: 1px solid #8884; }
code { font: 12px ui-monospace, monospace; }
tr.critical td:first-child { color: #c0392b; font-weight: 600; } tr.warning td:first-child { color: #b9770e; } tr.info td:first-child { opacity: .6; }
</style></head><body>
<h1>agent-works doctor: ${e(doc.project)}</h1>
<p>${e(doc.at)} · ${c.critical} critical · ${c.warning} warning · ${c.info} info · ${accepted.length} accepted · config: ${e(doc.config || "none (defaults)")}</p>
${rows.join("") || "<p>Clean.</p>"}
<h2>Sizes</h2><ul>${sizeItems}</ul>
</body></html>
`;
}

export async function main(argv, io) {
  io = ioOf(io);
  const { values, help } = parseArgs(argv, {
    json: { type: "boolean" }, baseline: { type: "boolean" }, html: { type: "string" }, all: { type: "boolean" }, accepted: { type: "boolean" },
    machine: { type: "boolean" },
  });
  if (help) {
    emit(io, USAGE);
    return 0;
  }
  if (values.machine) {
    const machine = await import("./machine-doctor.mjs");
    return machine.main(values.json ? ["--json"] : [], io);
  }
  const root = projectRoot(io.cwd);
  const res = await collect(root);
  const found = res.findings;
  const now = { sizes: { ...res.sizes, hubs: res.hubs }, codes: countsByCode(found) };
  const doc = {
    project: projectId(root), root: posix(root), config: res.config, at: nowIso(), failed: res.failed, sizes: now.sizes, codes: now.codes,
    accepted: res.accepted,
  };
  const file = baselinePath(root, io.env);
  const then = readJson(file);
  if (isObject(then)) doc.baseline = compare(now, then);
  if (values.baseline) {
    writeJson(file, { at: doc.at, project: doc.project, ...now });
    doc.baselineWritten = posix(file);
  }
  const full = findingsDoc(found, doc);
  if (values.html) atomicWrite(path.resolve(io.cwd, values.html), htmlReport(full, found));
  if (values.json) {
    emit(io, full, true);
  } else {
    emit(io, textReport(full, found, { max: values.all ? Infinity : 8, listAccepted: values.accepted === true }));
    if (values.html) emit(io, `report written: ${values.html}`);
  }
  const code = exitFor(found);
  return code === 2 ? 2 : Math.max(code, Object.keys(res.failed).length ? 1 : 0);
}

runMain(import.meta.url, main);
