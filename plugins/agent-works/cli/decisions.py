"""aw decisions: decision records and the glossary (core/references/decisions.md).

    aw decisions new "<title>" [--slug s] [--status proposed]   the next NNNN-slug.md from the template, titled as
                                                               the folder's latest records are (`# ADR 0014: T`)
    aw decisions index [--check] [--adopt]                     write the generated README.md index
    aw decisions lint [--json]                                 records, index and glossary

Records live in `paths.decisions` (default .agents/decisions), one decision per file `NNNN-slug.md` with the sections
Status, Sources, Context, Decision, Consequences. A record takes one amendment; after that a new record supersedes
it. The glossary is `paths.glossary` (default .agents/CONTEXT.md): one term per row, defined once.

Status and Sources are read as a `## Status` section or, in the common ADR form, as a line above the first section:
`- **Status:** accepted`, `**Status**: accepted`, `Status: accepted`, a frontmatter `status:` (the same for
`Sources` and `Date`; a date is added to the status in the index).

The index README.md is **generated** when one of its first lines is the marker `aw decisions index` writes
(GENERATED below). Any other README.md is **hand-written** and is never rewritten as a side effect: `new` appends one
line to it, and `index` refuses to run over it until it is told to with `--adopt` (as `aw memory index` does).

  DEC_NUMBER         a record whose name is not NNNN-slug.md, a number used twice, a heading with another number
  DEC_SECTIONS       a record without one of the five sections
  DEC_SIZE           a record over budgets.decisionLines
  DEC_AMENDED        more than one amendment section: write a new record that supersedes this one
  DEC_INDEX_STALE    README.md is missing, or a generated one differs from what `aw decisions index` writes
  DEC_INDEX_HANDWRITTEN  info: README.md is written by hand (kept as it is; `aw decisions index --adopt` converts it)
  GLOSSARY_MULTI     more than one glossary (the configured one, a root CONTEXT.md, one in the user docs)
  GLOSSARY_DUP_TERM  a term defined twice
  GLOSSARY_ROW_LONG  a row over budgets.glossaryRowChars
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

import common
from common import Finding

SECTIONS = ("Status", "Sources", "Context", "Decision", "Consequences")
NAME_RE = re.compile(r"^(\d{4})-([a-z0-9][a-z0-9-]*)\.md$")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
# The title forms in use: `# 0014. Title`, `# ADR 0014: Title`, `# 0014: Title`, `# 0014 - Title`, `# ADR-0014: Title`
TITLE = re.compile(r"^(ADR[\s-]*)?(\d{1,4})(\s*[.:—-]\s*)(.*)$", re.I)
FORM_FROM_LAST = 5  # `new` follows the majority form of this many latest records
INDEX = "README.md"
GENERATED = "<!-- Generated by `aw decisions index` from the records. Do not edit by hand. -->"
MARKER_WITHIN = 8  # the marker follows the title and the one paragraph under it
NO_RECORDS = "No records yet: `aw decisions new \"<title>\"` starts the first."
STUB_0_1_2 = f"# Decisions\n\n{NO_RECORDS}\n"  # what `aw setup` wrote before the stub carried the marker: ours too
# `- **Status:** accepted`, `**Status**: accepted`, `Status: accepted`, a frontmatter `status: accepted`
FIELD = re.compile(r"^\s*(?:[-*+]\s+)?(?:\*\*|__)?(status|sources?|date)\s*(?::\s*(?:\*\*|__)|(?:\*\*|__)\s*:|:)\s*(.*)$", re.I)
DATED = re.compile(r"\d{4}-\d{2}-\d{2}")


def index_kind(index: Path) -> str:
    """"missing", "generated" (it carries the marker, or is the stub of `aw setup`) or "handwritten"."""
    kind = common.index_kind(index, GENERATED, MARKER_WITHIN)
    if kind == "handwritten" and (common.read_text(index, "") or "").replace("\r\n", "\n").strip() == STUB_0_1_2.strip():
        return "generated"
    return kind


def decisions_dir(root: Path, cfg: Dict[str, Any]) -> Path:
    return common.config_path(cfg, root, "decisions")


def scan(root: Path, cfg: Dict[str, Any]) -> List[Dict[str, Any]]:
    """The records: {path, rel, file, number, slug, title, status, sections: {name: line}, amendments, lines, text}."""
    d = decisions_dir(root, cfg)
    out: List[Dict[str, Any]] = []
    if not d.is_dir():
        return out
    for p in sorted(d.iterdir()):
        if not p.is_file() or p.suffix.lower() != ".md" or p.name in (INDEX, "INDEX.md", "AGENTS.md", "CLAUDE.md"):
            continue
        text = common.read_text(p, "") or ""
        _, body = common.parse_frontmatter(text)
        m = NAME_RE.match(p.name)
        rec: Dict[str, Any] = {"path": p, "rel": common.rel(p, root), "file": p.name, "number": m.group(1) if m else None,
                               "slug": m.group(2) if m else None, "title": "", "heading_number": None, "status": "",
                               "title_form": None,
                               "sections": {}, "amendments": 0, "lines": common.line_count(text), "text": text}
        lines = text.splitlines()
        fenced = False
        fields: Dict[str, tuple] = {}  # the ADR form: Status / Sources / Date as a line above the first section
        head = True
        for n, line in enumerate(lines, 1):
            if re.match(r"^\s*(```|~~~)", line):
                fenced = not fenced
            h = None if fenced else HEADING.match(line)
            if not h:
                f = FIELD.match(line) if head and not fenced else None
                if f:
                    name = f.group(1).lower()
                    fields.setdefault("sources" if name == "source" else name, (n, " ".join(f.group(2).strip(" \t*_").split())))
                continue
            head = head and len(h.group(1)) < 2
            level, name = len(h.group(1)), h.group(2).strip()
            if level == 1 and not rec["title"]:
                t = TITLE.match(name)
                rec["title"] = (t.group(4) if t else name).strip()
                rec["heading_number"] = t.group(2).zfill(4) if t else None
                # (what stands before the number, is the number four digits, what stands between it and the title)
                rec["title_form"] = (t.group(1) or "", len(t.group(2)) == 4, t.group(3)) if t else None
            elif level >= 2:
                key = name.rstrip(":").strip().capitalize()
                if key in SECTIONS:
                    rec["sections"].setdefault(key, n)
                elif re.match(r"^(amendment|amended|update|addendum)\b", name, re.I):
                    rec["amendments"] += 1
        at = rec["sections"].get("Status")
        if at:
            for line in lines[at:]:
                if line.strip():
                    rec["status"] = "" if line.startswith("#") else " ".join(line.strip().split())
                    break
        elif "status" in fields:
            rec["status"] = fields["status"][1]
            date = fields.get("date", (0, ""))[1]
            if rec["status"] and date and not DATED.search(rec["status"]):
                rec["status"] += f" ({date})"
        for name in ("Status", "Sources"):
            if name.lower() in fields:
                rec["sections"].setdefault(name, fields[name.lower()][0])
        del body
        out.append(rec)
    return out


def build_index(records: List[Dict[str, Any]]) -> str:
    lines = ["# Decisions", "", "One record per decision, numbered in the order they were made. A record is amended once; "
             "after that a new record supersedes it.", "", GENERATED, ""]
    numbered = [r for r in records if r["number"] is not None]
    lines += [record_line(r) for r in numbered] or [NO_RECORDS]
    return "\n".join(lines).rstrip("\n") + "\n"


def record_line(r: Dict[str, Any]) -> str:
    """The line of a record in the index: the house format, also appended to a hand-written index."""
    status = f" — {r['status']}" if r["status"] else ""
    return f"- [{r['number']} — {r['title'] or r['slug']}]({r['file']}){status}"


def title_line(records: List[Dict[str, Any]], number: str, title: str) -> Optional[str]:
    """The heading of a new record in the form the folder uses: the majority form of its latest records (the newest
    wins a tie). None in a folder without titled records: the template's own form stands."""
    forms = [r["title_form"] for r in records if r["number"] is not None and r["title_form"]][-FORM_FROM_LAST:]
    if not forms:
        return None
    prefix, padded, sep = max(forms, key=lambda f: (forms.count(f), max(i for i, x in enumerate(forms) if x == f)))
    return f"# {prefix}{number if padded else int(number)}{sep}{title}"


def glossary_files(root: Path, cfg: Dict[str, Any]) -> List[Path]:
    main = common.config_path(cfg, root, "glossary")
    docs = common.config_path(cfg, root, "userDocs")
    seen, out = set(), []
    for p in (main, root / "CONTEXT.md", docs / "CONTEXT.md", root / ".agents" / "CONTEXT.md", docs / "glossary.md"):
        try:
            key = str(p.resolve()).lower()
        except OSError:
            key = str(p).lower()
        if key not in seen and p.is_file():
            seen.add(key)
            out.append(p)
    return out


def glossary_rows(text: str) -> List[tuple]:
    """(line number, term, the row) of a glossary: table rows, `- **Term** …` items and `**Term**: …` paragraphs."""
    rows = []
    fenced = False
    for n, line in enumerate(text.splitlines(), 1):
        if re.match(r"^\s*(```|~~~)", line):
            fenced = not fenced
            continue
        if fenced:
            continue
        s = line.strip()
        term = None
        if s.startswith("|"):
            cells = [c.strip() for c in s.strip("|").split("|")]
            if not cells or re.match(r"^:?-{2,}:?$", cells[0]) or cells[0].lower() in ("term", "word", "name", ""):
                continue
            term = cells[0]
        else:
            m = re.match(r"^(?:[-*+]\s+)?\*\*(.+?)\*\*", s)
            if m:
                term = m.group(1)
        if term:
            term = re.sub(r"[*`_]", "", term).strip().rstrip(":").strip()
            if term:
                rows.append((n, term, s))
    return rows


def findings(root: Path, cfg: Optional[Dict[str, Any]] = None) -> List[Finding]:
    cfg = cfg if cfg is not None else common.load_config(root)
    out: List[Finding] = []
    records = scan(root, cfg)
    d = decisions_dir(root, cfg)
    numbers: Dict[str, str] = {}
    for r in records:
        if r["number"] is None:
            out.append(Finding("DEC_NUMBER", "warning", r["rel"], 0, "the file name must be NNNN-slug.md (four digits, kebab-case slug)"))
        else:
            if r["number"] in numbers:
                out.append(Finding("DEC_NUMBER", "warning", r["rel"], 0, f"the number {r['number']} is also {numbers[r['number']]}"))
            numbers.setdefault(r["number"], r["file"])
            if r["heading_number"] and r["heading_number"] != r["number"]:
                out.append(Finding("DEC_NUMBER", "warning", r["rel"], 1, f"the heading says {r['heading_number']}, the file name {r['number']}"))
        missing = [s for s in SECTIONS if s not in r["sections"]]
        if missing:
            out.append(Finding("DEC_SECTIONS", "warning", r["rel"], 0, f"lacks the section{'s' if len(missing) > 1 else ''}: {', '.join(missing)}"))
        limit = common.budget(cfg, "decisionLines")
        if r["lines"] > limit:
            out.append(Finding("DEC_SIZE", "warning", r["rel"], 0, f"{r['lines']} lines, the budget is {limit}: a record holds one decision; measurements belong in memory"))
        if r["amendments"] > 1:
            out.append(Finding("DEC_AMENDED", "warning", r["rel"], 0,
                               f"{r['amendments']} amendment sections: a record takes one; write a new record that supersedes this one"))
    if records:
        have = common.read_text(d / INDEX)
        if have is not None and index_kind(d / INDEX) == "handwritten":
            n = common.lines_lost(have, build_index(records))
            out.append(Finding("DEC_INDEX_HANDWRITTEN", "info", common.rel(d / INDEX, root), 0,
                               f"written by hand ({n} line{'' if n == 1 else 's'} would be lost by generating it): `aw decisions "
                               "new` adds one line to it; `aw decisions index --adopt` converts it"))
        elif have is None or have.replace("\r\n", "\n") != build_index(records):
            out.append(Finding("DEC_INDEX_STALE", "warning", common.rel(d / INDEX, root), 0,
                               ("is missing" if have is None else "differs from the records") + " (aw decisions index)"))
    glossaries = glossary_files(root, cfg)
    if len(glossaries) > 1:
        out.append(Finding("GLOSSARY_MULTI", "warning", common.rel(glossaries[1], root), 0,
                           "more than one glossary: " + ", ".join(common.rel(g, root) for g in glossaries) +
                           f" (the one home is {common.rel(common.config_path(cfg, root, 'glossary'), root)})"))
    limit = common.budget(cfg, "glossaryRowChars")
    for g in glossaries:
        seen: Dict[str, int] = {}
        for n, term, row in glossary_rows(common.read_text(g, "") or ""):
            key = term.lower()
            if key in seen:
                out.append(Finding("GLOSSARY_DUP_TERM", "warning", common.rel(g, root), n, f"`{term}` is defined on line {seen[key]} too"))
            seen.setdefault(key, n)
            if len(row) > limit:
                out.append(Finding("GLOSSARY_ROW_LONG", "warning", common.rel(g, root), n,
                                   f"the row of `{term}` is {len(row)} characters, the budget is {limit}: define the word; the why goes into a decision"))
    return out


def write_index(root: Path, cfg: Dict[str, Any], adopt: bool = False) -> Optional[str]:
    """Write the index when it is missing, or generated and stale; a hand-written one only with ``adopt``."""
    records = scan(root, cfg)
    d = decisions_dir(root, cfg)
    if not d.is_dir() or (not adopt and index_kind(d / INDEX) == "handwritten"):
        return None
    text = build_index(records)
    have = common.read_text(d / INDEX)
    if have is not None and have.replace("\r\n", "\n") == text:
        return None
    common.atomic_write(d / INDEX, text)
    return common.rel(d / INDEX, root)


# ------------------------------------------------------------------------------------------------------- commands

def _ctx() -> tuple:
    root = common.project_root()
    return root, common.load_config(root)


def cmd_new(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    title = " ".join(args.title.split())
    slug = args.slug or re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:60].strip("-")
    if not slug or not re.match(r"^[a-z0-9][a-z0-9-]*$", slug):
        return common.fail("aw decisions new: the slug is kebab-case (give one with --slug)")
    records = scan(root, cfg)
    if any(r["slug"] == slug for r in records):
        return common.fail(f"aw decisions new: a record with the slug `{slug}` exists")
    number = f"{max([int(r['number']) for r in records if r['number']] or [0]) + 1:04d}"
    d = decisions_dir(root, cfg)
    path = d / f"{number}-{slug}.md"
    text = common.template("decision.md", number=number, title=title, status=args.status, date=common.today(), slug=slug)
    heading = title_line(records, number, title)
    if heading and text.startswith("# "):
        text = heading + "\n" + text.split("\n", 1)[1]  # the folder's own title form, so its index stays of one kind
    common.atomic_write(path, text)
    if index_kind(d / INDEX) == "handwritten":
        # A hand-written index says more than the records' titles: it gets this record's line and nothing else.
        rec = next(r for r in scan(root, cfg) if r["path"] == path)
        index = common.rel(d / INDEX, root) if common.append_list_line(d / INDEX, record_line(rec)) else None
    else:
        index = write_index(root, cfg)
    if args.json:
        common.emit({"path": common.rel(path, root), "number": number, "index": index}, True)
    else:
        print(common.rel(path, root))
    return 0


def cmd_index(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    if args.check:
        stale = [f for f in findings(root, cfg) if f.code in ("DEC_INDEX_STALE", "DEC_INDEX_HANDWRITTEN")]
        return common.report(stale, args.json, "decision index")
    index = decisions_dir(root, cfg) / INDEX
    by_hand = index_kind(index) == "handwritten"
    if by_hand and not args.adopt:
        where = common.rel(index, root)
        lost = common.lines_lost(common.read_text(index, "") or "", build_index(scan(root, cfg)))
        if args.json:
            common.emit({"refused": True, "handwritten": [{"path": where, "linesLost": lost}], "written": []}, True)
            return 2
        return common.fail("\n".join([
            f"aw decisions index: {where} is written by hand; nothing was written.",
            "Generating it replaces the whole file with one line per record (number, title, status): "
            f"{lost} line{' says' if lost == 1 else 's say'} something else today, and that text would be gone.",
            "First move what those lines say into the records, then run `aw decisions index --adopt`.",
            "Until then `aw decisions new` adds one line to this index and changes nothing else of it."]))
    changed = write_index(root, cfg, adopt=args.adopt)
    adopted = [changed] if changed and by_hand else []
    if args.json:
        common.emit({"written": [changed] if changed else [], "adopted": adopted}, True)
    else:
        print(f"{'adopted' if adopted else 'wrote'} {changed}" if changed else "the decision index is up to date")
    return 0


def cmd_lint(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    return common.report(findings(root, cfg), args.json, f"decisions: {len(scan(root, cfg))} records")


def register(subparsers: Any) -> None:
    p = subparsers.add_parser("decisions", help="decision records and the glossary: new, index, lint", description=__doc__,
                              formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="action", metavar="new|index|lint")
    s = sub.add_parser("new", help="start the next record")
    s.add_argument("title")
    s.add_argument("--slug")
    s.add_argument("--status", default="proposed")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_new)
    s = sub.add_parser("index", help="write the generated README.md index")
    s.add_argument("--check", action="store_true", help="exit 1 when a generated index is stale or it is missing; write nothing")
    s.add_argument("--adopt", action="store_true",
                   help="also convert an index written by hand to the generated one (the whole file is replaced)")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_index)
    s = sub.add_parser("lint", help="check the records, the index and the glossary")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_lint)
    p.set_defaults(func=lambda a: (p.print_help(), 2)[1])
