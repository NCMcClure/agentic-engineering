"""aw setup: set a repository up for agent work, or adopt one that already has agent files.

    aw setup --plan  [options]      print what would be created, changed and left alone; writes nothing
    aw setup --apply [options]      do it

    --twins generated|committed|off   CLAUDE.md twins (default: generated and git-ignored)
    --kanban tracked|ignored          the board is committed with the repository, or local (default: tracked)
    --move-board                      move an old .agents/board to .agents/kanban
    --install-launcher [DIR]          put an `aw` launcher into a folder on your PATH (see below)
    --json

What --apply writes: .agents/agent-works.json (its presence turns the guard on), .agents/README.md (the generated
contracts page, version-stamped), a root AGENTS.md if there is none, the memory tree with its status memory, the
decisions folder with its index, the glossary, lines in .gitignore, and the CLAUDE.md twins. It never overwrites a file
that is there (the generated .agents/README.md and indexes excepted), and it never moves a file by itself: agent
material found under the user docs (DOCS_AGENT_FILE) is reported with the `git mv` commands to run.

The launcher: Claude Code puts an enabled plugin's bin/ on the PATH of its Bash tool, so `aw` works there as it is.
It is not on the PATH of the PowerShell tool, of hooks, or of your own terminal: --install-launcher writes `aw` and
`aw.cmd` into DIR (default ~/.local/bin), which find the installed plugin each time they run.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import Any, Dict, List, Optional

import common

ALLOW_RULE = "Bash(aw:*)"


def template(name: str, **values: Any) -> str:
    """A setup template: the plugin's assets/templates/<name>, filled."""
    return common.template(name, **values)


def detect(root: Path, cfg: Dict[str, Any]) -> Dict[str, Any]:
    docs = common.config_path(cfg, root, "userDocs")
    root_claude = common.read_text(root / "CLAUDE.md")
    return {
        "git": common.repo_root(root) == root,
        "config": bool(cfg.get("_path")) and Path(cfg["_path"]).parent.parent == root,
        "agents": (root / "AGENTS.md").is_file(),
        "claudeOwn": root_claude is not None and root_claude.strip() != "@AGENTS.md",
        "memory": common.config_path(cfg, root, "memory").is_dir(),
        "decisions": common.config_path(cfg, root, "decisions").is_dir(),
        "glossary": common.config_path(cfg, root, "glossary").is_file(),
        "oldBoard": (root / common.OLD_KANBAN_REL / "board.json").is_file(),
        "kanban": common.config_path(cfg, root, "kanban").is_dir(),
        "docsAdr": next((common.rel(docs / n, root) for n in ("adr", "adrs", "decisions") if (docs / n).is_dir()), None),
        "docsGlossary": next((common.rel(p, root) for p in (docs / "CONTEXT.md", root / "CONTEXT.md") if p.is_file()), None),
        "plan": (root / ".plan").is_dir(),
        "perceptualLoop": (root / ".perceptual-loop").is_dir(),
    }


def _gitignore_has(root: Path, line: str) -> bool:
    text = common.read_text(root / ".gitignore", "") or ""
    return any(l.strip() == line for l in text.splitlines())


def plan(root: Path, opts: argparse.Namespace) -> Dict[str, Any]:
    """The steps as data: [{"do": create|append|regenerate|move|keep|report, "path", "why", …}]."""
    cfg = common.load_config(root)
    found = detect(root, cfg)
    twins_mode = opts.twins or (str((cfg.get("claude") or {}).get("twins")) if found["config"] else "generated")
    steps: List[Dict[str, Any]] = []
    R = lambda p: common.rel(p, root)  # noqa: E731

    def add(do: str, path: str, why: str, **more: Any) -> None:
        steps.append({"do": do, "path": path, "why": why, **more})

    if found["config"]:
        add("keep", common.CONFIG_REL, "the config is there; edit it by hand or with the guard skill")
    else:
        add("create", common.CONFIG_REL, "the config: its presence turns the guard on", text=template("config.json", twins=twins_mode))

    contract = root / ".agents" / "README.md"
    text = template("agents-readme.md", version=common.plugin_version(), project=root.name)
    have = common.read_text(contract)
    if have is None:
        add("create", R(contract), "the generated contracts page: which fact lives where", text=text)
    elif have.replace("\r\n", "\n") != text and ("agent-works contract v" in have):
        add("regenerate", R(contract), "generated by another version of the plugin", text=text)
    elif have.replace("\r\n", "\n") != text:
        add("report", R(contract), "exists and was not generated by agent-works: merge it into AGENTS.md or delete it, then run setup again")
    else:
        add("keep", R(contract), "up to date")

    if found["agents"]:
        n = common.line_count(common.read_text(root / "AGENTS.md", "") or "")
        limit = common.budget(cfg, "rootAgentsLines")
        add("keep", "AGENTS.md", f"yours ({n} lines" + (f", over the budget of {limit}: aw doctor says what to move" if n > limit else "") + ")")
    else:
        add("create", "AGENTS.md", "the root orientation file, to fill in", text=template("agents-root.md", project=root.name))

    memory = common.config_path(cfg, root, "memory")
    if found["memory"]:
        add("keep", R(memory), "the memory tree is there and stays as it is, indexes included; `aw memory lint` checks it")
    else:
        add("create", R(memory / "INDEX.md"), "the memory tree", text=template("memory-index.md"))
        add("create", R(memory / "project" / "INDEX.md"), "the folder of the status memory",
            text="# project/\n\nThe living status of the project and its plan.\n")
        add("create", R(memory / "project" / f"{common.today()}-project-status.md"), "the one status memory",
            text=template("status.md", slug="project-status", date=common.today(), title="Project status",
                          description="Goal, current focus and known issues: read at the start of every task"))

    decisions = common.config_path(cfg, root, "decisions")
    if found["decisions"]:
        add("keep", R(decisions), "decision records are there")
    elif found["docsAdr"]:
        add("report", found["docsAdr"], "DOCS_AGENT_FILE: decision records under the user docs. Move them yourself:",
            commands=[f"git mv {found['docsAdr']} {R(decisions)}", "aw decisions index", "aw links"])
    else:
        add("create", R(decisions / "README.md"), "the decisions folder and its generated index",
            text="# Decisions\n\nNo records yet: `aw decisions new \"<title>\"` starts the first.\n")

    glossary = common.config_path(cfg, root, "glossary")
    if found["glossary"]:
        add("keep", R(glossary), "the glossary is there")
    elif found["docsGlossary"]:
        add("report", found["docsGlossary"], "DOCS_AGENT_FILE: a glossary outside .agents/. Move it yourself:",
            commands=[f"git mv {found['docsGlossary']} {R(glossary)}", "aw links"])
    else:
        add("create", R(glossary), "the glossary", text=template("glossary.md"))

    new_board = common.config_path(cfg, root, "kanban")
    if found["oldBoard"] and not found["kanban"]:
        if opts.move_board:
            add("move", common.OLD_KANBAN_REL, f"KANBAN_OLD_FOLDER: the board moves to {R(new_board)}", to=R(new_board))
        else:
            add("report", common.OLD_KANBAN_REL, "KANBAN_OLD_FOLDER: the board is in its old folder (it keeps working). Move it "
                "with --move-board, or yourself:", commands=[f"git mv {common.OLD_KANBAN_REL} {R(new_board)}"])
    if found["plan"]:
        add("report", ".plan", "a but-first-planning workspace in its old place: its 4.0 skills move it to .agents/plan")
    if found["perceptualLoop"]:
        add("report", ".perceptual-loop", "perceptual-loop is in use: its locks are now `aw lock` (declare the applications under \"resources\" in the config)")

    if twins_mode == "generated":
        if found["claudeOwn"]:
            add("report", "CLAUDE.md", "has content of its own: move it into AGENTS.md and leave the one line `@AGENTS.md`, "
                "then `aw twins` (until then no twin is written over it)")
        if not _gitignore_has(root, "CLAUDE.md"):
            add("append", ".gitignore", "the CLAUDE.md twins are generated", text=template("gitignore-twins"))
        add("twins", "CLAUDE.md", "a CLAUDE.md that imports its sibling beside every AGENTS.md (aw twins)")
    elif twins_mode == "committed":
        add("twins", "CLAUDE.md", "a CLAUDE.md that imports its sibling beside every AGENTS.md, committed with them")
    if opts.kanban == "ignored" and not _gitignore_has(root, R(new_board) + "/"):
        add("append", ".gitignore", "a local board", text=template("gitignore-kanban").replace(".agents/kanban/", R(new_board) + "/"))

    return {"root": common.posix(root), "fresh": not (found["agents"] or found["memory"] or found["config"]),
            "found": found, "twins": twins_mode, "steps": steps,
            "next": ["aw doctor --baseline    (the first report, and the numbers later runs compare against)",
                     f"to let agents run aw without a prompt, add \"{ALLOW_RULE}\" to permissions.allow in your Claude Code "
                     "settings (yours to decide: it is not written for you)"]}


def apply(root: Path, doc: Dict[str, Any]) -> List[str]:
    done: List[str] = []
    for s in doc["steps"]:
        path = root / s["path"]
        if s["do"] == "create":
            if path.exists():
                continue  # never over a file that is there
            common.atomic_write(path, s["text"])
            done.append(f"created {s['path']}")
        elif s["do"] == "regenerate":
            common.atomic_write(path, s["text"])
            done.append(f"regenerated {s['path']}")
        elif s["do"] == "append":
            have = common.read_text(path, "") or ""
            common.atomic_write(path, have + ("" if not have or have.endswith("\n") else "\n") + ("\n" if have else "") + s["text"])
            done.append(f"added to {s['path']}")
        elif s["do"] == "move":
            to = root / s["to"]
            if not to.exists():
                to.parent.mkdir(parents=True, exist_ok=True)
                os.rename(path, to)
                done.append(f"moved {s['path']} to {s['to']}")
    cfg = common.load_config(root)
    if not doc["found"]["memory"]:
        # Only for the tree this run created. The lists of an existing tree's indexes may be written by hand and
        # say more than the memories' descriptions: they stay (MEM_INDEX_STALE), and `aw memory index` is a step
        # the reader takes knowingly.
        try:
            import memory

            done += [f"wrote {c}" for c in memory.write_indexes(root, cfg)]
        except Exception:
            pass
    if any(s["do"] == "twins" for s in doc["steps"]):
        try:
            import twins

            res = twins.heal(root, cfg)
            if res["written"]:
                done.append(f"wrote {len(res['written'])} CLAUDE.md twin{'s' if len(res['written']) != 1 else ''}")
            done += [f"! {f.path}: {f.message}" for f in res["findings"]]
        except Exception:
            pass
    return done


LAUNCHER_PY = ("import glob,os,runpy,sys;"
               "c=[p for p in [os.environ.get('AGENT_WORKS_CLI'),{baked!r}] if p and os.path.isfile(p)] or "
               "sorted(glob.glob(os.path.join(os.path.expanduser('~'),'.claude','plugins','cache','*','agent-works','*','cli','aw.py')),key=os.path.getmtime)[::-1];"
               "c or sys.exit('aw: agent-works is not installed (no cli/aw.py under ~/.claude/plugins/cache)');"
               "sys.argv[0]=c[0];runpy.run_path(c[0],run_name='__main__')")


def install_launcher(target: Optional[str], baked: Optional[str] = None) -> List[str]:
    """Write `aw` and `aw.cmd` into a PATH folder. They look the plugin up on each run, so an update needs no reinstall."""
    d = Path(target).expanduser() if target else Path.home() / ".local" / "bin"
    d.mkdir(parents=True, exist_ok=True)
    here = common.posix(Path(__file__).resolve().parent / "aw.py")
    if baked is None and "/plugins/cache/" not in here:
        baked = here  # a plugin loaded from a folder (development): the cache has no copy to find
    code = LAUNCHER_PY.format(baked=baked or "")
    sh = ("#!/bin/sh\n# aw: launcher of the agent-works CLI (written by `aw setup --install-launcher`).\n"
          "case \"$(command -v python3 2>/dev/null)\" in ''|*/WindowsApps/*) py=python ;; *) py=python3 ;; esac\n"
          # Git Bash and Cygwin: an exec leaves Python with a parent that is gone (see bin/aw).
          "case \"$(uname -s 2>/dev/null)\" in MINGW*|MSYS*|CYGWIN*) "
          f"\"$py\" -B -c \"{code}\" \"$@\"; exit $? ;; esac\n"
          f"exec \"$py\" -B -c \"{code}\" \"$@\"\n")
    cmd = ("@echo off\nrem aw: launcher of the agent-works CLI (written by `aw setup --install-launcher`).\nsetlocal\nset \"AW_PY=\"\n"
           "for /f \"delims=\" %%i in ('where python3 python 2^>nul') do (\n  if not defined AW_PY (\n"
           "    echo %%i | findstr /i /c:\"WindowsApps\" >nul || set \"AW_PY=%%i\"\n  )\n)\n"
           "if not defined AW_PY (\n  echo aw: no Python 3 on the PATH 1>&2\n  exit /b 127\n)\n"
           f"\"%AW_PY%\" -B -c \"{code}\" %*\nexit /b %ERRORLEVEL%\n")
    out = []
    for name, text in (("aw", sh), ("aw.cmd", cmd)):
        common.atomic_write(d / name, text)
        if name == "aw":
            try:
                os.chmod(d / name, 0o755)
            except OSError:
                pass
        out.append(common.posix(d / name))
    on_path = any(os.path.normcase(os.path.abspath(p)) == os.path.normcase(str(d.resolve())) for p in os.environ.get("PATH", "").split(os.pathsep) if p)
    if not on_path:
        out.append(f"note: {common.posix(d)} is not on your PATH yet")
    return out


def text_of(doc: Dict[str, Any], applied: Optional[List[str]]) -> str:
    kind = "a fresh repository" if doc["fresh"] else "a repository that has agent files"
    lines = [f"aw setup — {doc['root']} ({kind}; CLAUDE.md twins: {doc['twins']})", ""]
    marks = {"create": "create    ", "append": "add to    ", "regenerate": "regenerate", "move": "move      ", "keep": "keep      ",
             "report": "REPORT    ", "twins": "twins     "}
    for s in doc["steps"]:
        lines.append(f"  {marks[s['do']]} {s['path']}" + (f" -> {s['to']}" if s.get("to") else "") + f"   {s['why']}")
        lines += [f"               {c}" for c in s.get("commands") or []]
    lines.append("")
    if applied is None:
        lines.append("Nothing was written. `aw setup --apply` does the create / add / regenerate / move / twins steps; REPORT steps are yours.")
    else:
        lines += applied or ["nothing to do: everything is in place"]
    lines += ["", "next:"] + [f"  {n}" for n in doc["next"]]
    return "\n".join(lines)


def run(args: argparse.Namespace) -> int:
    if args.install_launcher is not None and not (args.plan or args.apply):
        for line in install_launcher(args.install_launcher or None):
            print(line)
        return 0
    if args.plan == args.apply:
        return common.fail("aw setup: say --plan (print what would happen) or --apply (do it)")
    root = common.repo_root() or Path.cwd().resolve()
    cfg_at = common.find_config()
    if cfg_at is not None:
        root = cfg_at.parent.parent
    doc = plan(root, args)
    applied = apply(root, doc) if args.apply else None
    if args.apply and args.install_launcher is not None:
        applied = (applied or []) + install_launcher(args.install_launcher or None)
    if args.json:
        slim = {**doc, "steps": [{k: v for k, v in s.items() if k != "text"} for s in doc["steps"]], "applied": applied}
        common.emit(slim, True)
    else:
        common.emit(text_of(doc, applied))
    return 0


def register(subparsers: Any) -> None:
    p = subparsers.add_parser("setup", help="set a repository up for agent work, or adopt an existing one",
                              description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--plan", action="store_true", help="print what would be created and changed; write nothing")
    p.add_argument("--apply", action="store_true", help="write it")
    p.add_argument("--twins", choices=["generated", "committed", "off"])
    p.add_argument("--kanban", choices=["tracked", "ignored"], default="tracked")
    p.add_argument("--move-board", action="store_true", help="move an old .agents/board to the kanban folder")
    p.add_argument("--install-launcher", nargs="?", const="", metavar="DIR", help="write aw and aw.cmd into DIR (default ~/.local/bin)")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=run)
