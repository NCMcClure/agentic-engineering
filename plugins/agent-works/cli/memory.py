"""aw memory: the project's long-term memory, kept to its contract (core/references/memory.md).

    aw memory lint [--json]                                  check the tree
    aw memory index [--check]                                write every INDEX.md from the memories' frontmatter
    aw memory new <folder> <slug> --type T --description D   start a memory (and its folder, if new)
    aw memory touch <slug>                                   a memory changed: bump `updated`, rename, fix links

The tree is `paths.memory` (default .agents/memory): category folders, one topic per file named
`<YYYY-MM-DD>-<slug>.md`, frontmatter `name` (= the slug), `description`, `type`, `updated` (= the date prefix), and
an INDEX.md at every level. The lists of an INDEX.md are generated; its description line is written by hand.

  MEM_FRONTMATTER       a memory without the four fields, with an unknown type, or whose date and `updated` differ
  MEM_NAME_MISMATCH     the file name is not <date>-<slug>.md, or `name` is not the slug
  MEM_SLUG_DUP          two memories with one slug (a slug is the memory's identity across the tree)
  MEM_ROOT_LOOSE        a memory at the root of the tree (memories live in category folders)
  MEM_FOLDER_OVER       a folder with more memories than budgets.memoryFolderFiles: split it
  MEM_FILE_SIZE         a memory over budgets.memoryFileLines
  MEM_HOOK_LONG         a description over budgets.indexHookChars (it is the index line)
  MEM_LINK_DANGLING     a [[slug]] that names no memory
  MEM_INDEX_STALE       an INDEX.md that is missing or differs from what `aw memory index` writes
  MEM_SHARED_CANDIDATE  info: tagged machine or tooling, so it may belong in the shared learnings (aw learn add)
  STATUS_SIZE           the status memory over budgets.statusLines (critical beyond three times the budget)
  STATUS_DONE_SECTION   the status memory keeps a Done section (done is the git log and closed cards: aw status)
  STATUS_MULTI          more than one memory of type status
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import common
from common import Finding

TYPES = ("status", "decision", "learning", "report", "reference")  # also the order of an index
NAME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z0-9][a-z0-9-]*)\.md$")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
LINK_RE = re.compile(r"\[\[([a-z0-9][a-z0-9-]*)\]\]")
CODE_RE = re.compile(r"`[^`]*`")
DONE_RE = re.compile(r"^#{1,6}\s+(Done|Completed|Changelog|History)\b", re.I)
SHARED_TAGS = {"machine", "tooling"}
FOLDER_INTRO = "<one line: what belongs in this folder>"
GENERATED = "<!-- The lists below are generated by `aw memory index` from the memories' frontmatter. -->"


def memory_root(root: Path, cfg: Dict[str, Any]) -> Path:
    return common.config_path(cfg, root, "memory")


def scan(root: Path, cfg: Dict[str, Any]) -> Dict[str, Any]:
    """The tree as data: {"dir", "folders": [Path], "memories": [entry], "loose": [Path]}.

    An entry: {path, rel (to the repository), folder (Path), file, date, slug, fields (None without frontmatter),
    body, lines, text}.
    """
    base = memory_root(root, cfg)
    out: Dict[str, Any] = {"dir": base, "folders": [], "memories": [], "loose": []}
    if not base.is_dir():
        return out

    def visit(d: Path) -> None:
        try:
            entries = sorted(d.iterdir())
        except OSError:
            return
        for e in entries:
            if e.is_dir():
                if not e.name.startswith("."):
                    out["folders"].append(e)
                    visit(e)
            elif e.suffix.lower() == ".md" and e.name != "INDEX.md":
                text = common.read_text(e, "") or ""
                fields, body = common.parse_frontmatter(text)
                m = NAME_RE.match(e.name)
                entry = {"path": e, "rel": common.rel(e, root), "folder": d, "file": e.name,
                         "date": m.group(1) if m else None, "slug": m.group(2) if m else None,
                         "fields": fields, "body": body, "lines": common.line_count(text), "text": text}
                (out["loose"] if d == base else out["memories"]).append(entry)

    visit(base)
    return out


def _type_of(entry: Dict[str, Any]) -> str:
    return str((entry["fields"] or {}).get("type") or "")


def _intro(index: Path, default: str) -> str:
    """The hand-written description line of an INDEX.md: its first paragraph that is no heading, link or list."""
    text = common.read_text(index)
    for line in (text or "").splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "-", "*", "<!--", "Parent:", "|")):
            continue
        return s
    return default


def build_index(d: Path, tree: Dict[str, Any]) -> str:
    base: Path = tree["dir"]
    is_root = d == base
    title = "# Memory index" if is_root else f"# {d.name}/"
    default = ("Decisions, measured facts, lessons and status of this project: one line per category folder."
               if is_root else FOLDER_INTRO)
    lines = [title, "", _intro(d / "INDEX.md", default), ""]
    if not is_root:
        lines += ["Parent: [../INDEX.md](../INDEX.md)", ""]
    lines += [GENERATED, ""]
    subs = sorted(f for f in tree["folders"] if f.parent == d)
    for f in subs:
        lines.append(f"- [{f.name}/]({f.name}/INDEX.md) — {_intro(f / 'INDEX.md', FOLDER_INTRO)}")
    mine = [m for m in tree["memories"] if m["folder"] == d]

    def key(m: Dict[str, Any]) -> tuple:
        t = _type_of(m)
        return (TYPES.index(t) if t in TYPES else len(TYPES), m["slug"] or m["file"])

    for m in sorted(mine, key=key):
        f = m["fields"] or {}
        hook = " ".join(str(f.get("description") or "<no description>").split())
        lines.append(f"- [{m['slug'] or m['file'][:-3]}]({m['file']}) — {_type_of(m) or '?'} — {hook}")
    return "\n".join(lines).rstrip("\n") + "\n"


def indexes(tree: Dict[str, Any]) -> Dict[Path, str]:
    """Every INDEX.md the tree should hold, as text."""
    if not tree["dir"].is_dir():
        return {}
    return {d / "INDEX.md": build_index(d, tree) for d in [tree["dir"], *tree["folders"]]}


def findings(root: Path, cfg: Optional[Dict[str, Any]] = None) -> List[Finding]:
    cfg = cfg if cfg is not None else common.load_config(root)
    tree = scan(root, cfg)
    out: List[Finding] = []
    if not tree["dir"].is_dir():
        return out
    B = lambda k: common.budget(cfg, k)  # noqa: E731
    for e in tree["loose"]:
        out.append(Finding("MEM_ROOT_LOOSE", "warning", e["rel"], 0,
                           "a memory at the root of the tree: move it into the category folder that fits"))
    slugs: Dict[str, List[Dict[str, Any]]] = {}
    for e in tree["memories"]:
        if e["slug"]:
            slugs.setdefault(e["slug"], []).append(e)
    status = [e for e in tree["memories"] if _type_of(e) == "status"]
    for e in tree["memories"]:
        f, rel = e["fields"], e["rel"]
        if e["slug"] is None:
            out.append(Finding("MEM_NAME_MISMATCH", "warning", rel, 0, "the file name must be <YYYY-MM-DD>-<slug>.md (kebab-case slug)"))
        if f is None:
            out.append(Finding("MEM_FRONTMATTER", "warning", rel, 1, "no frontmatter: name, description, type, updated"))
            continue
        missing = [k for k in ("name", "description", "type", "updated") if not str(f.get(k) or "").strip()]
        if missing:
            out.append(Finding("MEM_FRONTMATTER", "warning", rel, 1, f"frontmatter lacks: {', '.join(missing)}"))
        if f.get("type") and f["type"] not in TYPES:
            out.append(Finding("MEM_FRONTMATTER", "warning", rel, 1, f"type \"{f['type']}\" is not one of: {', '.join(TYPES)}"))
        if e["date"] and f.get("updated") and str(f["updated"]) != e["date"]:
            out.append(Finding("MEM_FRONTMATTER", "warning", rel, 1,
                               f"`updated: {f['updated']}` and the file name's date {e['date']} differ (aw memory touch {e['slug']})"))
        if e["slug"] and f.get("name") and f["name"] != e["slug"]:
            out.append(Finding("MEM_NAME_MISMATCH", "warning", rel, 1, f"`name: {f['name']}` is not the file's slug `{e['slug']}`"))
        hook = " ".join(str(f.get("description") or "").split())
        if len(hook) > B("indexHookChars"):
            out.append(Finding("MEM_HOOK_LONG", "warning", rel, 1,
                               f"the description is {len(hook)} characters, the budget is {B('indexHookChars')}: it is the "
                               "index line, say what is in the file and when it matters"))
        if _type_of(e) == "status":
            limit = B("statusLines")
            if e["lines"] > limit:
                out.append(Finding("STATUS_SIZE", "critical" if e["lines"] > 3 * limit else "warning", rel, 0,
                                   f"{e['lines']} lines, the budget is {limit}: goal, current focus, known issues as "
                                   "card links; lessons move to topic memories"))
            for n, line in enumerate(e["text"].splitlines(), 1):
                if DONE_RE.match(line):
                    out.append(Finding("STATUS_DONE_SECTION", "warning", rel, n,
                                       "a Done section: what is done is the git log and the closed cards (aw status)"))
                    break
        elif e["lines"] > B("memoryFileLines"):
            out.append(Finding("MEM_FILE_SIZE", "warning", rel, 0,
                               f"{e['lines']} lines, the budget is {B('memoryFileLines')}: one topic per file, split it"))
        for n, line in enumerate(e["text"].splitlines(), 1):
            for m in LINK_RE.finditer(CODE_RE.sub("", line)):  # `[[slug]]` in code is talk about the syntax
                if m.group(1) not in slugs:
                    out.append(Finding("MEM_LINK_DANGLING", "warning", rel, n, f"[[{m.group(1)}]] names no memory"))
        tags = f.get("tags") or []
        tags = {str(t).lower() for t in (tags if isinstance(tags, list) else re.split(r"[,\s]+", str(tags)))}
        if tags & SHARED_TAGS:
            out.append(Finding("MEM_SHARED_CANDIDATE", "info", rel, 0,
                               "tagged machine/tooling: if it holds for other projects too, publish it with `aw learn add`"))
    for slug, entries in sorted(slugs.items()):
        if len(entries) > 1:
            where = ", ".join(x["rel"] for x in entries)
            out.append(Finding("MEM_SLUG_DUP", "warning", entries[1]["rel"], 0, f"the slug `{slug}` is used twice: {where}"))
    if len(status) > 1:
        out.append(Finding("STATUS_MULTI", "warning", status[1]["rel"], 0,
                           "more than one memory of type status: " + ", ".join(x["rel"] for x in status)))
    for d in tree["folders"]:
        n = sum(1 for e in tree["memories"] if e["folder"] == d)
        if n > B("memoryFolderFiles"):
            out.append(Finding("MEM_FOLDER_OVER", "warning", common.rel(d, root), 0,
                               f"{n} memories, the budget is {B('memoryFolderFiles')}: split the folder where it clearly divides"))
    for path, text in sorted(indexes(tree).items()):
        have = common.read_text(path)
        if have is None or have.replace("\r\n", "\n") != text:
            out.append(Finding("MEM_INDEX_STALE", "warning", common.rel(path, root), 0,
                               ("is missing" if have is None else "differs from the memories' frontmatter") + " (aw memory index)"))
    return out


def write_indexes(root: Path, cfg: Dict[str, Any]) -> List[str]:
    changed = []
    for path, text in sorted(indexes(scan(root, cfg)).items()):
        have = common.read_text(path)
        if have is None or have.replace("\r\n", "\n") != text:
            common.atomic_write(path, text)
            changed.append(common.rel(path, root))
    return changed


# ------------------------------------------------------------------------------------------------------- commands

def _ctx() -> tuple:
    root = common.project_root()
    return root, common.load_config(root)


def cmd_lint(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    tree = scan(root, cfg)
    if not tree["dir"].is_dir() and not args.json:
        print(f"aw memory: no {common.rel(tree['dir'], root)} here (aw setup --plan)")
        return 0
    return common.report(findings(root, cfg), args.json, f"memory: {len(tree['memories'])} memories in {len(tree['folders'])} folders")


def cmd_index(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    if args.check:
        stale = [f for f in findings(root, cfg) if f.code == "MEM_INDEX_STALE"]
        return common.report(stale, args.json, "memory indexes")
    changed = write_indexes(root, cfg)
    if args.json:
        common.emit({"written": changed}, True)
    else:
        print("\n".join(f"wrote {c}" for c in changed) or "memory indexes are up to date")
    return 0


def cmd_new(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    if not SLUG_RE.match(args.slug) or not SLUG_RE.match(args.folder):
        return common.fail("aw memory new: folder and slug are kebab-case (lower-case letters, digits, '-')")
    tree = scan(root, cfg)
    clash = [e for e in tree["memories"] + tree["loose"] if e["slug"] == args.slug]
    if clash:
        return common.fail(f"aw memory new: the slug `{args.slug}` exists: {clash[0]['rel']} (update it: aw memory touch {args.slug})")
    if args.type == "status" and any(_type_of(e) == "status" for e in tree["memories"]):
        return common.fail("aw memory new: there is a status memory already; a project has one")
    folder = tree["dir"] / args.folder
    date = common.today()
    path = folder / f"{date}-{args.slug}.md"
    title = args.title or args.slug.replace("-", " ").capitalize()
    name = "status.md" if args.type == "status" else "memory-file.md"
    text = common.template(name, slug=args.slug, description=" ".join(args.description.split()),
                           type=args.type, date=date, title=title)
    folder.mkdir(parents=True, exist_ok=True)
    common.atomic_write(path, text)
    if not (folder / "INDEX.md").is_file() and args.about:
        common.atomic_write(folder / "INDEX.md", f"# {args.folder}/\n\n{' '.join(args.about.split())}\n")
    changed = write_indexes(root, cfg)
    if args.json:
        common.emit({"path": common.rel(path, root), "indexes": changed}, True)
    else:
        print(common.rel(path, root))
        if not args.about and _intro(folder / "INDEX.md", "<") .startswith("<"):
            print(f"note: describe the folder in the first line of {common.rel(folder / 'INDEX.md', root)}")
    return 0


def cmd_touch(args: argparse.Namespace) -> int:
    root, cfg = _ctx()
    tree = scan(root, cfg)
    found = [e for e in tree["memories"] + tree["loose"] if e["slug"] == args.slug]
    if len(found) != 1:
        return common.fail(f"aw memory touch: {'no' if not found else 'more than one'} memory with the slug `{args.slug}`")
    e = found[0]
    date = args.date or common.today()
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", date):
        return common.fail("aw memory touch: --date is YYYY-MM-DD")
    text = e["text"]
    if e["fields"] is not None and "updated" in e["fields"]:
        text = re.sub(r"(?m)^updated:.*$", f"updated: {date}", text, count=1)
    elif e["fields"] is not None:
        text = re.sub(r"\A(---[ \t]*\r?\n.*?)(\r?\n---)", lambda m: f"{m.group(1)}\nupdated: {date}{m.group(2)}", text, count=1, flags=re.S)
    new_name = f"{date}-{args.slug}.md"
    new_path = e["path"].with_name(new_name)
    fixed: List[str] = []
    if new_name != e["file"]:
        if new_path.exists():
            return common.fail(f"aw memory touch: {common.rel(new_path, root)} exists already")
        common.atomic_write(new_path, text)
        e["path"].unlink()
        # Links name the exact file: fix them wherever the repository's Markdown has one.
        for md in common.markdown_files(root):
            if md == new_path or md.name == "INDEX.md" and tree["dir"] in md.parents:
                continue
            body = common.read_text(md)
            if body and e["file"] in body:
                common.atomic_write(md, body.replace(e["file"], new_name))
                fixed.append(common.rel(md, root))
    elif text != e["text"]:
        common.atomic_write(e["path"], text)
    changed = write_indexes(root, cfg)
    if args.json:
        common.emit({"path": common.rel(new_path, root), "renamedFrom": e["rel"] if new_name != e["file"] else None,
                     "linksFixed": fixed, "indexes": changed}, True)
    else:
        print(common.rel(new_path, root) + (f"  (was {e['file']})" if new_name != e["file"] else "  (already dated today)"))
        for f in fixed:
            print(f"fixed links in {f}")
    return 0


def register(subparsers: Any) -> None:
    p = subparsers.add_parser("memory", help="project memory: lint, index, new, touch", description=__doc__,
                              formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="action", metavar="lint|index|new|touch")
    s = sub.add_parser("lint", help="check the memory tree against its contract")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_lint)
    s = sub.add_parser("index", help="write every INDEX.md from the memories' frontmatter")
    s.add_argument("--check", action="store_true", help="exit 1 when an index is stale; write nothing")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_index)
    s = sub.add_parser("new", help="start a memory")
    s.add_argument("folder", help="the category folder (created when new)")
    s.add_argument("slug", help="kebab-case, unique across the tree, never changes")
    s.add_argument("--type", required=True, choices=TYPES)
    s.add_argument("--description", required=True, help="one line: what is in it and when it matters (the index line)")
    s.add_argument("--title")
    s.add_argument("--about", help="for a new folder: one line saying what belongs in it")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_new)
    s = sub.add_parser("touch", help="a memory's content changed: bump `updated`, rename the file, fix links")
    s.add_argument("slug")
    s.add_argument("--date", help="YYYY-MM-DD (default: today)")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_touch)
    p.set_defaults(func=lambda a: (p.print_help(), 2)[1])
